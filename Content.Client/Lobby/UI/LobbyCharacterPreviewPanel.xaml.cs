namespace Content.Client.Lobby.UI;

[GenerateTypedNameReferences]
public sealed partial class LobbyCharacterPreviewPanel : Control
{
    private static readonly Color SummaryColor = Color.FromHex("#9A9A9A");

    public Button CharacterSetupButton => CharacterSetup;

    public LobbyCharacterPreviewPanel()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
    }

    public void SetLoaded(bool value)
    {
        Loaded.Visible = value;
        Unloaded.Visible = !value;
    }

    public void SetSummaryText(string value)
    {
        // Summary is a RichTextLabel (a Label with ClipText measures zero wide and vanishes); FromUnformatted escapes player markup.
        Summary.SetMessage(FormattedMessage.FromUnformatted(value), defaultColor: SummaryColor);
    }
}
