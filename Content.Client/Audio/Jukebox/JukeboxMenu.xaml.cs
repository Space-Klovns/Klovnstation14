{
    [Dependency] private readonly IEntityManager _entManager = default!;
    [Dependency] private readonly IConfigurationManager _cfg = default!; // _sin
    private AudioSystem _audioSystem;

    /// <summary>
    /// Are we currently 'playing' or paused for the play / pause button.
    /// </summary>
    private bool _playState;

    /// <summary>
    /// True if playing, false if paused.
    /// </summary>
    public event Action<bool>? OnPlayPressed;
    public event Action? OnStopPressed;
    public event Action<ProtoId<JukeboxPrototype>>? OnSongSelected;
    public event Action<float>? SetTime;
    // _sin start
    public event Action<float>? SetVolume;
    public event Action<bool>? OnAutoplayChanged;
    public event Action<List<ProtoId<JukeboxPrototype>>>? OnQueueChanged;

    /// <summary>
    /// Sends the current queue to the server. Call this when a track is selected.
    /// </summary>
    public void SendQueueUpdate()
    {
        var queue = BuildQueue();
        OnQueueChanged?.Invoke(queue);
    }
