    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (_lockTimer > 0f)
        {
            _lockTimer -= args.DeltaSeconds;
        }

        PlaybackSlider.Disabled = _lockTimer > 0f;


        if (_entManager.TryGetComponent(_audio, out AudioComponent? audio))
        {
            DurationLabel.Text = $@"{TimeSpan.FromSeconds(audio.PlaybackPosition):mm\:ss} / {_audioSystem.GetAudioLength(audio.FileName):mm\:ss}";
        }
        else
        {
            DurationLabel.Text = $"00:00 / 00:00";
        }

        if (PlaybackSlider.Grabbed)
            return;

        // _sin start
        // Ensure audio is resolved even when skipping slider update (needed for SetPlayPauseButton).
        if (audio == null)
            _entManager.TryGetComponent(_audio, out audio);

        // Don't update slider position while the lock timer is active — prevents visual bounce-back
        // while waiting for the server to confirm the new playback position.
        if (_lockTimer <= 0f)
        {
            PlaybackSlider.SetValueWithoutEvent(audio?.PlaybackPosition ?? 0f);
        }
        // _sin end

        SetPlayPauseButton(_audioSystem.IsPlaying(_audio, audio));
    }

    public void SetSelectedSongText(string? text)
    {
        if (!string.IsNullOrEmpty(text))
        {
            SongName.Text = text;
        }
        else
        {
            SongName.Text = "---";
        }
    }
