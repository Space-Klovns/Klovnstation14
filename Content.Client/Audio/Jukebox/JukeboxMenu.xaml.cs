    /// <summary>
    /// Builds the queue from the current filtered list, starting from the selected track,
    /// wrapping circularly and collecting only unique tracks (max 200).
    /// </summary>
    public List<ProtoId<JukeboxPrototype>> BuildQueue()
    {
        var tracks = GetCurrentFilteredTracks();
        var result = new List<ProtoId<JukeboxPrototype>>();

        if (tracks.Count == 0)
            return result;

        // Find index of selected track
        var startIndex = 0;
        if (_selectedTrackId != null)
        {
            var idx = tracks.FindIndex(t => t.ID == _selectedTrackId);
            if (idx >= 0)
                startIndex = idx;
        }

        // Collect unique tracks by wrapping circularly, up to 200 or all unique tracks
        var unique = new HashSet<string>();
        for (var i = 0; i < 200 && unique.Count < tracks.Count; i++)
        {
            var index = (startIndex + i) % tracks.Count;
            var id = tracks[index].ID;
            if (unique.Add(id))
                result.Add(id);
        }

        return result;
    }

    /// <summary>
    /// Gets the currently filtered track list based on active tab and search.
    /// </summary>
    private List<JukeboxPrototype> GetCurrentFilteredTracks()
    {
        if (_activeTab == JukeboxTab.Favorites)
        {
            // Favorites tab
            return _allProtos
                .Where(p => _favorites.Contains(p.ID))
                .ToList();
        }
        else if (_activeTab == JukeboxTab.Main && _currentGroup != null)
        {
            // Group view - filter by group tags
            return _allProtos
                .Where(p => _currentGroup.GroupSearchTag.Any(gt =>
                    p.SearchTag.Any(st => st.Contains(gt, StringComparison.OrdinalIgnoreCase)) ||
                    p.Name.Contains(gt, StringComparison.OrdinalIgnoreCase)))
                .ToList();
        }
        else
        {
            // Main tab - filter by search bar text
            var query = SearchBar.Text;
            if (string.IsNullOrEmpty(query))
            {
                return _allProtos.ToList();
            }

            return _allProtos
                .Where(p => p.Name.Contains(query, StringComparison.OrdinalIgnoreCase) ||
                            p.ID.Contains(query, StringComparison.OrdinalIgnoreCase) ||
                            p.SearchTag.Any(tag => tag.Contains(query, StringComparison.OrdinalIgnoreCase)))
                .ToList();
        }
    }
