using System.Numerics;
using Content.Client._KS14.Tgui.Controls;
using Content.Client.UserInterface.Controls;
using Content.Shared._KS14.SalvageTablet;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;

namespace Content.Client._KS14.SalvageTablet;

/// <summary>
///     The details of one S.P.A.M. task: what to bring or kill, the reward, how far along it is and the time left,
///         with a button to take it on and one to throw it away.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class KsSalvageTabletTaskWindow : FancyWindow
{
    [Dependency] private IGameTiming _gameTiming = default!;
    [Dependency] private IPrototypeManager _prototypeManager = default!;

    public event Action<ProtoId<KsSalvageTaskPrototype>>? OnTrack;
    public event Action<ProtoId<KsSalvageTaskPrototype>>? OnDrop;

    private readonly EntityPrototypeView _iconView;
    private readonly KsTguiProgressBar _progressBar;
    private readonly Label _rewardLabel;
    private readonly Label _timeLabel;

    private TimeSpan? _endTime;
    private TimeSpan _nextDropTime;
    private int _shownSeconds = -1;
    private int _shownDropSeconds = -1;

    /// <summary>
    ///     The task on show.
    /// </summary>
    public ProtoId<KsSalvageTaskPrototype> Task { get; private set; }

    public KsSalvageTabletTaskWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _iconView = new EntityPrototypeView
        {
            SetSize = new Vector2(160, 160),
            Scale = new Vector2(4, 4),
            HorizontalAlignment = HAlignment.Center,
        };
        IconHost.AddChild(KsSalvageTabletTaskCard.MakePlaque(_iconView));

        _rewardLabel = new Label();
        _progressBar = new KsTguiProgressBar { MinValue = 0, MaxValue = 1 };
        _timeLabel = new Label();

        var text = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, SeparationOverride = 6 };
        text.AddChild(_rewardLabel);
        text.AddChild(_progressBar);
        text.AddChild(_timeLabel);
        TextHost.AddChild(KsSalvageTabletTaskCard.MakePlaque(text));

        TrackButton.OnPressed += _ => OnTrack?.Invoke(Task);
        DropButton.ConfirmText = Loc.GetString("ks-salvage-tablet-confirm");
        DropButton.Confirmed += () => OnDrop?.Invoke(Task);
    }

    /// <param name="canTrack">Whether the account has room to track another task.</param>
    public void SetTask(KsSalvageActiveTask task, TimeSpan nextDropTime, bool canTrack)
    {
        Task = task.Task;
        _endTime = task.EndTime;
        _nextDropTime = nextDropTime;
        _shownSeconds = -1;
        _shownDropSeconds = -1;
        _progressBar.Value = task.Amount > 0 ? task.Progress / (float)task.Amount : 0f;
        _progressBar.Text = Loc.GetString("ks-salvage-tablet-task-progress", ("progress", task.Progress), ("amount", task.Amount));

        TrackButton.Disabled = task.Tracked || !canTrack;
        TrackButton.Text = Loc.GetString(task.Tracked
            ? "ks-salvage-tablet-task-tracked"
            : canTrack
                ? "ks-salvage-tablet-task-track"
                : "ks-salvage-tablet-task-track-full");

        if (!_prototypeManager.TryIndex(task.Task, out var taskPrototype))
            return;

        Title = Loc.GetString(taskPrototype.Name);
        _iconView.SetPrototype(taskPrototype.Icon);
        _rewardLabel.Text = Loc.GetString("ks-salvage-tablet-task-reward-long",
            ("points", taskPrototype.PointsPerUnit * task.Amount),
            ("reputation", taskPrototype.Reputation));

        if (task.EndTime == null)
            _timeLabel.Text = Loc.GetString("ks-salvage-tablet-task-duration-long", ("time", FormatTime(taskPrototype.Duration)));
    }

    /// <summary>
    ///     A time as tgui writes one (<see cref="KsTguiTimeDisplay.FormatTime"/>), never below zero.
    /// </summary>
    public static string FormatTime(TimeSpan time)
    {
        if (time < TimeSpan.Zero)
            time = TimeSpan.Zero;

        // tgui counts in deciseconds.
        return KsTguiTimeDisplay.FormatTime((float)(time.TotalSeconds * 10.0));
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        var curTime = _gameTiming.CurTime;
        if (_endTime is { } endTime)
        {
            var timeLeft = endTime - curTime;
            var seconds = Math.Max((int)timeLeft.TotalSeconds, 0);
            if (seconds != _shownSeconds)
            {
                _shownSeconds = seconds;
                _timeLabel.Text = Loc.GetString("ks-salvage-tablet-task-time-left", ("time", FormatTime(timeLeft)));
            }
        }

        var dropWait = _nextDropTime - curTime;
        var dropSeconds = Math.Max((int)Math.Ceiling(dropWait.TotalSeconds), 0);
        if (dropSeconds == _shownDropSeconds)
            return;

        _shownDropSeconds = dropSeconds;
        DropButton.Disabled = dropSeconds > 0;
        if (dropSeconds > 0)
            DropButton.Disarm();

        // An armed button is asking to confirm, and puts its own text back when it is done.
        if (DropButton.Armed)
            return;

        DropButton.Text = dropSeconds > 0
            ? Loc.GetString("ks-salvage-tablet-task-drop-wait", ("time", FormatTime(dropWait)))
            : Loc.GetString("ks-salvage-tablet-task-drop");
    }
}
