namespace Content.Client._KS14.SPAM;

/// <summary>
///     The S.P.A.M. tablet's screen: a login prompt with a short boot sequence, then the silo on the left, the tasks in
///         a row at the top right, and the salvager with their rank and points below them.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class KsSPAMWindow : FancyWindow
{
    [Dependency] private IEntityManager _entityManager = default!;
    [Dependency] private IGameTiming _gameTiming = default!;
    [Dependency] private IPrototypeManager _prototypeManager = default!;

    /// <summary>
    ///     How long the boot sequence plays after Log in is pressed.
    /// </summary>
    public static readonly TimeSpan BootDuration = TimeSpan.FromSeconds(1.5);

    private static readonly LocId[] BootLines =
    [
        "ks-spam-login-reading",
        "ks-spam-login-checking",
        "ks-spam-login-loading",
    ];

    public event Action? OnLogin;
    public event Action? OnLogout;

    /// <summary>
    ///     The boot sequence ended with the account on the screen.
    /// </summary>
    public event Action? OnLoggedIn;

    /// <summary>
    ///     The details of a task were opened.
    /// </summary>
    public event Action? OnTaskShown;
    public event Action<ProtoId<KsSPAMTaskPrototype>>? OnTrack;
    public event Action<ProtoId<KsSPAMTaskPrototype>>? OnDrop;
    public event Action<Dictionary<ProtoId<KsSPAMProductPrototype>, int>>? OnOrder;

    private readonly List<KsSPAMTaskCard> _taskCards = [];
    private readonly Dictionary<ProtoId<MaterialPrototype>, KsSPAMMaterialRow> _materialRows = [];
    private KsSPAMTaskWindow? _taskWindow;
    private KsSPAMOrderWindow? _orderWindow;
    private KsSPAMBuiState _state = new();
    private ProtoId<KsSPAMRankLadderPrototype> _ladderId;
    private int _maxOrderAmount = 1;
    private int _maxTrackedTasks = 1;
    private int _lowMaterialAmount;

    /// <summary>
    ///     When Log in was pressed, while the boot sequence plays.
    /// </summary>
    private TimeSpan? _bootStart;

    public KsSPAMWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        LoginButton.OnPressed += _ =>
        {
            _bootStart = _gameTiming.RealTime;
            OnLogin?.Invoke();
            RefreshScreen();
        };
        LogoutButton.OnPressed += _ => OnLogout?.Invoke();
        OrderButton.OnPressed += _ => ShowOrders();
        OnClose += CloseSubWindows;
    }

    /// <summary>
    ///     Closes the task and order windows. They are windows of their own, so nothing closes them when the server
    ///         closes the tablet: that disposes this window without <see cref="BaseWindow.OnClose"/> ever firing.
    /// </summary>
    public void CloseSubWindows()
    {
        _taskWindow?.Close();
        _orderWindow?.Close();
    }

    public void UpdateState(KsSPAMBuiState state, KsSPAMComponent spamComponent)
    {
        _state = state;
        _ladderId = spamComponent.RankLadder;
        _maxOrderAmount = spamComponent.MaxOrderAmount;
        _maxTrackedTasks = spamComponent.MaxTrackedTasks;
        _lowMaterialAmount = spamComponent.LowMaterialAmount;
        RefreshScreen();

        if (!state.LoggedIn)
        {
            CloseSubWindows();
            return;
        }

        OwnerNameLabel.Text = state.OwnerName;
        JobLabel.Text = state.JobTitle;
        PointsLabel.Text = Loc.GetString("ks-spam-profile-points", ("points", state.Points));
        OwnerView.SetEntity(_entityManager.GetEntity(state.Owner));

        var rank = UpdateRank(state.Reputation);
        UpdateNextUnlocks(rank);
        UpdateTasks(state);
        UpdateMaterials(state);

        if (_orderWindow is { IsOpen: true })
            _orderWindow.UpdateState(state.Points, rank, state.NextOrderTime, _maxOrderAmount);
    }

    /// <returns>The rank, counted from zero.</returns>
    private int UpdateRank(int reputation)
    {
        if (!_prototypeManager.TryIndex(_ladderId, out var ladderPrototype) || ladderPrototype.Ranks.Count == 0)
            return 0;

        var rank = ladderPrototype.GetRank(reputation);
        RankLabel.Text = Loc.GetString("ks-spam-profile-rank", ("rank", Loc.GetString(ladderPrototype.Ranks[rank].Title)));

        if (rank + 1 >= ladderPrototype.Ranks.Count)
        {
            ReputationBar.Value = 1f;
            ReputationLabel.Text = Loc.GetString("ks-spam-profile-reputation-max", ("reputation", reputation));
            return rank;
        }

        var rankStart = ladderPrototype.Ranks[rank].Reputation;
        var nextRank = ladderPrototype.Ranks[rank + 1].Reputation;
        ReputationBar.Value = nextRank > rankStart ? (reputation - rankStart) / (float)(nextRank - rankStart) : 1f;
        ReputationLabel.Text = Loc.GetString("ks-spam-profile-reputation", ("reputation", reputation), ("next", nextRank));
        return rank;
    }

    /// <summary>
    ///     What the next rank adds to the order list.
    /// </summary>
    private void UpdateNextUnlocks(int rank)
    {
        var names = new List<string>();
        foreach (var productPrototype in _prototypeManager.EnumeratePrototypes<KsSPAMProductPrototype>())
        {
            if (productPrototype.MinRank == rank + 1 && _prototypeManager.TryIndex(productPrototype.Entity, out var entityPrototype))
                names.Add(entityPrototype.Name);
        }

        NextUnlocksLabel.Visible = names.Count > 0;
        if (names.Count == 0)
            return;

        names.Sort(string.Compare);
        NextUnlocksLabel.SetMessage(FormattedMessage.FromUnformatted(
            Loc.GetString("ks-spam-profile-next-unlocks", ("items", string.Join(", ", names)))));
    }

    private int TrackedCount()
    {
        var tracked = 0;
        foreach (var task in _state.Tasks)
        {
            if (task.Tracked)
                tracked++;
        }

        return tracked;
    }

    private void UpdateTasks(KsSPAMBuiState state)
    {
        NoTasksLabel.Visible = state.Tasks.Count == 0;
        TaskScroll.Visible = state.Tasks.Count > 0;
        TrackedLabel.Text = Loc.GetString("ks-spam-tasks-tracked", ("tracked", TrackedCount()), ("max", _maxTrackedTasks));

        while (_taskCards.Count > state.Tasks.Count)
        {
            var last = _taskCards[^1];
            _taskCards.RemoveAt(_taskCards.Count - 1);
            TaskContainer.RemoveChild(last);
        }

        while (_taskCards.Count < state.Tasks.Count)
        {
            var card = new KsSPAMTaskCard();
            card.OnPressed += _ => ShowTask(card.Task);
            _taskCards.Add(card);
            TaskContainer.AddChild(card);
        }

        for (var slot = 0; slot < state.Tasks.Count; slot++)
        {
            _taskCards[slot].SetTask(state.Tasks[slot], _prototypeManager);
        }

        if (_taskWindow is not { IsOpen: true })
            return;

        // The task on show was finished, failed or dropped.
        if (FindTask(_taskWindow.Task) is { } shown)
            _taskWindow.SetTask(shown, state.NextDropTime, TrackedCount() < _maxTrackedTasks);
        else
            _taskWindow.Close();
    }

    private KsSPAMActiveTask? FindTask(ProtoId<KsSPAMTaskPrototype> taskId)
    {
        foreach (var task in _state.Tasks)
        {
            if (task.Task == taskId)
                return task;
        }

        return null;
    }

    private void UpdateMaterials(KsSPAMBuiState state)
    {
        NoSiloLabel.Visible = state.Materials.Count == 0;

        var spriteSystem = _entityManager.System<SpriteSystem>();
        var materialStorageSystem = _entityManager.System<MaterialStorageSystem>();

        // Rows are kept from one state to the next: a state arrives every second, and a rebuilt row loses its tooltip.
        var seen = new HashSet<ProtoId<MaterialPrototype>>();
        foreach (var material in state.Materials)
        {
            if (!_prototypeManager.TryIndex(material.Material, out var materialPrototype))
                continue;

            seen.Add(material.Material);
            if (!_materialRows.TryGetValue(material.Material, out var row))
            {
                row = new KsSPAMMaterialRow(materialPrototype, spriteSystem);
                _materialRows[material.Material] = row;
                MaterialContainer.AddChild(row);
            }

            row.Update(material, materialPrototype, materialStorageSystem, _lowMaterialAmount);
        }

        foreach (var (materialId, row) in _materialRows.ToList())
        {
            if (seen.Contains(materialId))
                continue;

            _materialRows.Remove(materialId);
            MaterialContainer.RemoveChild(row);
        }

        // What has been asked for first, then what is running low, then by name.
        var position = 0;
        foreach (var row in _materialRows.Values
                     .OrderByDescending(row => row.Requested)
                     .ThenByDescending(row => row.Low)
                     .ThenBy(row => MaterialName(row.Material)))
        {
            row.SetPositionInParent(position++);
        }
    }

    private string MaterialName(ProtoId<MaterialPrototype> materialId)
    {
        return _prototypeManager.TryIndex(materialId, out var materialPrototype)
            ? Loc.GetString(materialPrototype.Name)
            : materialId.Id;
    }

    private void ShowTask(ProtoId<KsSPAMTaskPrototype> taskId)
    {
        if (FindTask(taskId) is not { } task)
            return;

        if (_taskWindow == null)
        {
            _taskWindow = new KsSPAMTaskWindow();
            _taskWindow.OnTrack += shownTaskId => OnTrack?.Invoke(shownTaskId);
            _taskWindow.OnDrop += shownTaskId => OnDrop?.Invoke(shownTaskId);
        }

        _taskWindow.SetTask(task, _state.NextDropTime, TrackedCount() < _maxTrackedTasks);
        if (!_taskWindow.IsOpen)
            _taskWindow.OpenCentered();

        OnTaskShown?.Invoke();
    }

    /// <summary>
    ///     Opens the order window, which is a window of its own.
    /// </summary>
    public void ShowOrders()
    {
        if (_orderWindow == null)
        {
            _orderWindow = new KsSPAMOrderWindow();
            _orderWindow.OnOrder += cart => OnOrder?.Invoke(cart);
        }

        var rank = _prototypeManager.TryIndex(_ladderId, out var ladderPrototype) ? ladderPrototype.GetRank(_state.Reputation) : 0;
        _orderWindow.UpdateState(_state.Points, rank, _state.NextOrderTime, _maxOrderAmount);
        if (!_orderWindow.IsOpen)
            _orderWindow.OpenCentered();
    }

    /// <summary>
    ///     Which of the three screens shows: the prompt, the boot sequence or the account.
    /// </summary>
    private void RefreshScreen()
    {
        var booting = _bootStart != null;
        MainBox.Visible = _state.LoggedIn && !booting;
        LoginBox.Visible = !MainBox.Visible;
        LoginButton.Visible = !booting;
        LoginProgressBar.Visible = booting;

        if (!booting)
            LoginStatusLabel.Text = Loc.GetString("ks-spam-login-prompt");
    }

    /// <summary>
    ///     The window opens at the size of the login prompt and grows a lot once the account shows and fills in, past
    ///         the bottom of the screen. Moves it back just far enough, leaving it where the player put it otherwise.
    /// </summary>
    protected override void Resized()
    {
        base.Resized();

        if (Parent == null)
            return;

        var position = Vector2.Clamp(Position, Vector2.Zero, Vector2.Max(Parent.Size - Size, Vector2.Zero));
        if (position != Position)
            LayoutContainer.SetPosition(this, position);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        var curTime = _gameTiming.CurTime;
        foreach (var card in _taskCards)
        {
            card.UpdateTime(curTime);
        }

        if (_bootStart is not { } bootStart)
            return;

        var progress = (float)((_gameTiming.RealTime - bootStart) / BootDuration);
        if (progress >= 1f)
        {
            // A refused login leaves the state logged out, and the prompt comes back.
            _bootStart = null;
            RefreshScreen();
            if (_state.LoggedIn)
                OnLoggedIn?.Invoke();

            return;
        }

        LoginProgressBar.Value = progress;
        LoginStatusLabel.Text = Loc.GetString(BootLines[Math.Min((int)(progress * BootLines.Length), BootLines.Length - 1)]);
    }
}
