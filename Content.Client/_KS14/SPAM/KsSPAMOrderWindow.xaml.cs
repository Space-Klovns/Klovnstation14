namespace Content.Client._KS14.SPAM;

/// <summary>
///     Where a salvager spends mining points. Two tabs, as on tgstation's mining order console: the catalogue of what
///         their rank may order, each with a button that adds it to the cart, and the cart, which is where amounts
///         are changed and the lot is ordered, dropped next to them by pod.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class KsSPAMOrderWindow : FancyWindow
{
    [Dependency] private IGameTiming _gameTiming = default!;
    [Dependency] private IPrototypeManager _prototypeManager = default!;

    /// <summary>
    ///     The cart, sent when the order button is pressed.
    /// </summary>
    public event Action<Dictionary<ProtoId<KsSPAMProductPrototype>, int>>? OnOrder;

    private readonly Dictionary<ProtoId<KsSPAMProductPrototype>, int> _cart = [];
    private readonly ButtonGroup _categoryGroup = new();
    private LocId? _category;
    private int _points;
    private int _rank;
    private int _maxAmount = 1;
    private TimeSpan _nextOrderTime;
    private int _shownWaitSeconds = -1;

    /// <summary>
    ///     Whether an order was sent and the server has yet to accept it. The cart is kept until it does, so a
    ///         refused order loses nothing.
    /// </summary>
    private bool _orderSent;

    /// <summary>
    ///     What is in the cart, for whoever needs to look and not touch.
    /// </summary>
    public IReadOnlyDictionary<ProtoId<KsSPAMProductPrototype>, int> Cart => _cart;

    public KsSPAMOrderWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        SearchEdit.OnTextChanged += _ => PopulateProducts();
        CatalogueTabButton.OnPressed += _ => ShowCart(false);
        CartTabButton.OnPressed += _ => ShowCart(true);
        ClearButton.OnPressed += _ =>
        {
            _cart.Clear();
            CartChanged();
        };
        OrderButton.OnPressed += _ =>
        {
            if (_cart.Count == 0)
                return;

            _orderSent = true;
            OnOrder?.Invoke(new Dictionary<ProtoId<KsSPAMProductPrototype>, int>(_cart));
        };

        PopulateCategories();
        PopulateProducts();
        CartChanged();
    }

    public void UpdateState(int points, int rank, TimeSpan nextOrderTime, int maxAmount)
    {
        var rankChanged = rank != _rank;

        // The order cooldown only moves forward when the server takes an order.
        var accepted = _orderSent && nextOrderTime > _nextOrderTime;

        _points = points;
        _rank = rank;
        _nextOrderTime = nextOrderTime;
        _maxAmount = Math.Max(maxAmount, 1);

        if (accepted)
        {
            _cart.Clear();
            CartChanged();
            ShowCart(false);
        }

        if (rankChanged)
            PopulateProducts();

        UpdateTotals();
    }

    /// <summary>
    ///     Adds to, or takes from, how many of a product are in the cart.
    /// </summary>
    public void ChangeAmount(ProtoId<KsSPAMProductPrototype> productId, int by)
    {
        var amount = Math.Clamp(_cart.GetValueOrDefault(productId) + by, 0, _maxAmount);
        if (amount == 0)
            _cart.Remove(productId);
        else
            _cart[productId] = amount;

        CartChanged();
    }

    private void ShowCart(bool cart)
    {
        CartBox.Visible = cart;
        CatalogueBox.Visible = !cart;
        CartTabButton.Pressed = cart;
        CatalogueTabButton.Pressed = !cart;
    }

    private void CartChanged()
    {
        // A changed cart is a new order, whatever became of the last one.
        _orderSent = false;

        var count = 0;
        foreach (var amount in _cart.Values)
        {
            count += amount;
        }

        CartTabButton.Text = Loc.GetString("ks-spam-order-tab-cart", ("count", count));
        EmptyCartLabel.Visible = _cart.Count == 0;
        ClearButton.Disabled = _cart.Count == 0;

        CartContainer.RemoveAllChildren();
        foreach (var (productId, amount) in _cart.OrderBy(entry => ProductName(entry.Key)))
        {
            if (_prototypeManager.TryIndex(productId, out var productPrototype))
                CartContainer.AddChild(MakeCartRow(productPrototype, amount));
        }

        UpdateTotals();
    }

    private string ProductName(ProtoId<KsSPAMProductPrototype> productId)
    {
        return _prototypeManager.TryIndex(productId, out var productPrototype) &&
               _prototypeManager.TryIndex(productPrototype.Entity, out var entityPrototype)
            ? entityPrototype.Name
            : productId.Id;
    }

    private void PopulateCategories()
    {
        var categories = _prototypeManager.EnumeratePrototypes<KsSPAMProductPrototype>()
            .Select(productPrototype => productPrototype.Category)
            .Distinct()
            .OrderBy(category => Loc.GetString(category))
            .ToList();

        _category = categories.Count > 0 ? categories[0] : (LocId?)null;
        foreach (var category in categories)
        {
            var button = new Button
            {
                Text = Loc.GetString(category),
                ToggleMode = true,
                Group = _categoryGroup,
                Pressed = category == _category,
                StyleClasses = { StyleClass.ButtonSquare },
            };
            button.OnPressed += _ =>
            {
                _category = category;
                PopulateProducts();
            };
            CategoryContainer.AddChild(button);
        }
    }

    private void PopulateProducts()
    {
        ProductContainer.RemoveAllChildren();

        // A search looks through every category, as tgstation's does.
        var search = SearchEdit.Text.Trim();
        var products = new List<(KsSPAMProductPrototype Product, EntityPrototype Entity)>();
        foreach (var productPrototype in _prototypeManager.EnumeratePrototypes<KsSPAMProductPrototype>())
        {
            if (!_prototypeManager.TryIndex(productPrototype.Entity, out var entityPrototype))
                continue;

            if (search.Length > 0
                    ? !entityPrototype.Name.Contains(search, StringComparison.CurrentCultureIgnoreCase)
                    : productPrototype.Category != _category)
                continue;

            products.Add((productPrototype, entityPrototype));
        }

        foreach (var (productPrototype, entityPrototype) in products
                     .OrderBy(product => product.Product.MinRank)
                     .ThenBy(product => product.Product.Cost)
                     .ThenBy(product => product.Entity.Name))
        {
            ProductContainer.AddChild(MakeProductRow(productPrototype, entityPrototype));
        }
    }

    /// <summary>
    ///     The start of a row in either list: the picture and the name of a product.
    /// </summary>
    private BoxContainer MakeRow(KsSPAMProductPrototype productPrototype, EntityPrototype entityPrototype, bool weak)
    {
        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            SeparationOverride = 8,
            ToolTip = entityPrototype.Description,
            MouseFilter = MouseFilterMode.Pass,
        };

        var iconView = new EntityPrototypeView
        {
            SetSize = new Vector2(36, 36),
            VerticalAlignment = VAlignment.Center,
        };
        iconView.SetPrototype(productPrototype.Entity);
        row.AddChild(iconView);

        var nameLabel = new Label
        {
            Text = entityPrototype.Name,
            HorizontalExpand = true,
            VerticalAlignment = VAlignment.Center,
            ClipText = true,
        };
        if (weak)
            nameLabel.StyleClasses.Add(StyleClass.LabelWeak);
        row.AddChild(nameLabel);
        return row;
    }

    private BoxContainer MakeProductRow(KsSPAMProductPrototype productPrototype, EntityPrototype entityPrototype)
    {
        var locked = productPrototype.MinRank > _rank;
        var row = MakeRow(productPrototype, entityPrototype, weak: locked);

        if (locked)
        {
            row.AddChild(new Label
            {
                Text = Loc.GetString("ks-spam-order-locked", ("rank", productPrototype.MinRank + 1)),
                VerticalAlignment = VAlignment.Center,
                StyleClasses = { StyleClass.LabelWeak },
            });
            return row;
        }

        row.AddChild(new Label
        {
            Text = Loc.GetString("ks-spam-order-cost", ("cost", productPrototype.Cost)),
            VerticalAlignment = VAlignment.Center,
            MinWidth = 70,
        });

        var addButton = new Button
        {
            Text = Loc.GetString("ks-spam-order-add"),
            VerticalAlignment = VAlignment.Center,
            StyleClasses = { StyleClass.ButtonSquare },
        };
        ProtoId<KsSPAMProductPrototype> productId = productPrototype.ID;
        addButton.OnPressed += _ => ChangeAmount(productId, 1);
        row.AddChild(addButton);
        return row;
    }

    private BoxContainer MakeCartRow(KsSPAMProductPrototype productPrototype, int amount)
    {
        if (!_prototypeManager.TryIndex(productPrototype.Entity, out var entityPrototype))
            return new BoxContainer();

        var row = MakeRow(productPrototype, entityPrototype, weak: false);
        row.AddChild(new Label
        {
            Text = Loc.GetString("ks-spam-order-cost", ("cost", productPrototype.Cost * amount)),
            VerticalAlignment = VAlignment.Center,
            MinWidth = 70,
        });

        ProtoId<KsSPAMProductPrototype> productId = productPrototype.ID;
        var minusButton = MakeAmountButton("-", enabled: true);
        var amountLabel = new Label
        {
            Text = amount.ToString(),
            MinWidth = 24,
            Align = Label.AlignMode.Center,
            VerticalAlignment = VAlignment.Center,
        };
        var plusButton = MakeAmountButton("+", enabled: amount < _maxAmount);
        var removeButton = new Button
        {
            Text = Loc.GetString("ks-spam-order-remove"),
            StyleClasses = { StyleClass.ButtonSquare, StyleClass.Negative },
        };

        minusButton.OnPressed += _ => ChangeAmount(productId, -1);
        plusButton.OnPressed += _ => ChangeAmount(productId, 1);
        removeButton.OnPressed += _ => ChangeAmount(productId, -amount);

        row.AddChild(minusButton);
        row.AddChild(amountLabel);
        row.AddChild(plusButton);
        row.AddChild(removeButton);
        return row;
    }

    /// <summary>
    ///     A bare symbol with no plate behind it, as the lathe's x5 and x10 are. Faded when it can't be used.
    /// </summary>
    private static KsTguiButton MakeAmountButton(string symbol, bool enabled)
    {
        var button = new KsTguiButton
        {
            Text = symbol,
            Color = KsTguiColor.Transparent,
            Compact = true,
            MinWidth = 20,
            VerticalAlignment = VAlignment.Center,
            Disabled = !enabled,
            Modulate = enabled ? Color.White : Color.White.WithAlpha(KsTguiPalettes.Translucent(Color.White, 0.5f, KsTguiPalettes.Base).A),
        };

        // Only the tgui sheet styles a transparent tgui button; Baron would give it its own plate. The cart is rebuilt
        //      on every change, so a theme switch catches up on the next one.
        if (!KsTguiTheme.ReadEnabled())
        {
            button.StyleBoxOverride = new StyleBoxEmpty();
            button.ModulateSelfOverride = Color.White;
        }

        return button;
    }

    private int CartTotal()
    {
        var total = 0;
        foreach (var (productId, amount) in _cart)
        {
            if (_prototypeManager.TryIndex(productId, out var productPrototype))
                total += productPrototype.Cost * amount;
        }

        return total;
    }

    private void UpdateTotals()
    {
        TotalLabel.Text = Loc.GetString("ks-spam-order-total", ("total", CartTotal()));
        PointsLabel.Text = Loc.GetString("ks-spam-profile-points", ("points", _points));
        _shownWaitSeconds = -1;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        var wait = _nextOrderTime - _gameTiming.CurTime;
        var waitSeconds = Math.Max((int)Math.Ceiling(wait.TotalSeconds), 0);
        if (waitSeconds == _shownWaitSeconds)
            return;

        _shownWaitSeconds = waitSeconds;
        var total = CartTotal();
        OrderButton.Disabled = waitSeconds > 0 || total <= 0 || total > _points;
        OrderButton.Text = waitSeconds > 0
            ? Loc.GetString("ks-spam-order-button-wait", ("time", KsSPAMTaskWindow.FormatTime(wait)))
            : Loc.GetString("ks-spam-order-button");
    }
}
