    /// <summary>
    ///     The wheel's zoom target, exposed for the prefs write-through: the public
    ///         WorldRange is the lerped display value, which mid-glide is not what
    ///         the crew dialled.
    /// </summary>
    public float KsTargetRange => ActualRadarRange;

    /// <summary>
    ///     Restores a remembered zoom in one step: setting WorldRange alongside the
    ///         target skips the wheel lerp, so a reopened console snaps to its old
    ///         range instead of visibly gliding there.
    /// </summary>
    public void KsRestoreRange(float range)
    {
        ActualRadarRange = Math.Clamp(range, WorldMinRange, WorldMaxRange);
        WorldRange = ActualRadarRange;
    }

    protected override void KeyBindUp(GUIBoundKeyEventArgs args)
    {
        base.KeyBindUp(args);

        if (_coordinates == null || _rotation == null || args.Function != EngineKeyFunctions.UIClick ||
            OnRadarClick == null)
        {
            return;
        }

        var a = InverseScalePosition(args.RelativePosition);
        var relativeWorldPos = new Vector2(a.X, -a.Y);
        relativeWorldPos = _rotation.Value.RotateVec(relativeWorldPos);
        var coords = _coordinates.Value.Offset(relativeWorldPos);
        OnRadarClick?.Invoke(coords);
    }

    [PublicAPI]
    public EntityCoordinates GetMouseCoordinates(ScreenCoordinates screen)
    {
        if (_coordinates == null || _rotation == null)
        {
            return EntityCoordinates.Invalid;
        }

        var pos = screen.Position / UIScale - GlobalPosition;

        var a = InverseScalePosition(pos);
        var relativeWorldPos = new Vector2(a.X, -a.Y);
        relativeWorldPos = _rotation.Value.RotateVec(relativeWorldPos);
        var coords = _coordinates.Value.Offset(relativeWorldPos);
        return coords;
    }

    public void UpdateState(NavInterfaceState state)
    {
        SetMatrix(EntManager.GetCoordinates(state.Coordinates), state.Angle);

        WorldMaxRange = state.MaxRange;

        if (WorldMaxRange < WorldRange)
        {
            ActualRadarRange = WorldMaxRange;
        }

        if (WorldMaxRange < WorldMinRange)
            WorldMinRange = WorldMaxRange;

        ActualRadarRange = Math.Clamp(ActualRadarRange, WorldMinRange, WorldMaxRange);

        RotateWithEntity = state.RotateWithEntity;

        _docks = state.Docks;

        // Sensor contacts are the sole source of foreign-grid visibility. A null
        // sensor picture (no coverage) reads back as the old all-null/false defaults.
        _ksContacts = state.KsSensorNav?.Contacts;
        _ksSensorRegions = state.KsSensorNav?.Regions;
        _ksJammed = state.KsSensorNav?.Jammed ?? false;
        _ksTransitions.Update(_ksContacts, _timing.CurTime);
        _ksLiveContacts.Clear();
        if (_ksContacts != null)
        {
            foreach (var contact in _ksContacts)
            {
                // Real-hull gate: only an Exact-quality live track may draw the actual
                // grid. Letting a bearing track draw the PVS-replicated hull would put
                // the target at its true position and leak what the server withheld.
                if (contact.Live && contact.Quality == KsPositionQuality.Exact)
                    _ksLiveContacts.Add(contact.Grid);
            }
        }
    }

    protected override void Draw(DrawingHandleScreen handle)
    {
        base.Draw(handle);

        KsDrawInstrumentFace(handle);

        // Drawn before the nav picture so it survives when jamming has left the radar
        // with nothing to show.
        KsDrawJammedIndicator(handle);

        if (_coordinates == null || _rotation == null)
        {
            return;
        }

        var xformQuery = EntManager.GetEntityQuery<TransformComponent>();
        var fixturesQuery = EntManager.GetEntityQuery<FixturesComponent>();

        if (!xformQuery.TryGetComponent(_coordinates.Value.EntityId, out var xform)
            || xform.MapID == MapId.Nullspace)
        {
            return;
        }

        var mapPos = _transform.ToMapCoordinates(_coordinates.Value);
        var posMatrix = Matrix3Helpers.CreateTransform(_coordinates.Value.Position, _rotation.Value);
        var ourEntRot = RotateWithEntity ? _transform.GetWorldRotation(xform) : _rotation.Value;
        var ourEntMatrix = Matrix3Helpers.CreateTransform(_transform.GetWorldPosition(xform), ourEntRot);
        var shuttleToWorld = Matrix3x2.Multiply(posMatrix, ourEntMatrix);
        Matrix3x2.Invert(shuttleToWorld, out var worldToShuttle);
        var shuttleToView = Matrix3x2.CreateScale(new Vector2(MinimapScale, -MinimapScale)) * Matrix3x2.CreateTranslation(MidPointVector);

        var ourGridId = xform.GridUid;
        if (EntManager.TryGetComponent<MapGridComponent>(ourGridId, out var ourGrid))
        {
            var ourGridToWorld = _transform.GetWorldMatrix(ourGridId.Value);
            var ourGridToShuttle = Matrix3x2.Multiply(ourGridToWorld, worldToShuttle);
            var ourGridToView = ourGridToShuttle * shuttleToView;
            var color = _shuttles.GetIFFColor(ourGridId.Value, self: true);

            KsDrawInterests(handle, ourGridToView, new Box2(mapPos.Position - MaxRadarRangeVector, mapPos.Position + MaxRadarRangeVector), (ourGridId.Value, ourGrid));

            // Coverage fans, under the hull and contacts.
            KsDrawSensorRegions(handle, ourGridToView, worldToShuttle * shuttleToView, EntManager.GetNetEntity(ourGridId.Value));

            if (fixturesQuery.HasComponent(ourGridId.Value))
            {
                DrawGrid(handle, ourGridToView, (ourGridId.Value, ourGrid), color);
                DrawDocks(handle, ourGridId.Value, ourGridToView);
            }
        }

        const float radarVertRadius = 2f;
        var radarPosVerts = new Vector2[]
        {
            ScalePosition(new Vector2(0f, -radarVertRadius)),
            ScalePosition(new Vector2(radarVertRadius / 2f, 0f)),
            ScalePosition(new Vector2(0f, radarVertRadius)),
            ScalePosition(new Vector2(radarVertRadius / -2f, 0f)),
        };

        handle.DrawPrimitives(DrawPrimitiveTopology.TriangleFan, radarPosVerts, KsHud.SelfPosition);

        var rot = ourEntRot + _rotation.Value;
        var viewBounds = new Box2Rotated(new Box2(-WorldRange, -WorldRange, WorldRange, WorldRange).Translated(mapPos.Position), rot, mapPos.Position);
        var viewAABB = viewBounds.CalcBoundingBox();

        _grids.Clear();
        _mapManager.FindGridsIntersecting(xform.MapID, new Box2(mapPos.Position - MaxRadarRangeVector, mapPos.Position + MaxRadarRangeVector), ref _grids, approx: true, includeMap: false);

        _ksRealDrawn.Clear();

        // Full fog of war: a foreign grid renders as a real hull only when the console's
        // grid has a live sensor track on it; everything else is the contact layer's job.
        // Replaces the vanilla CanDraw/IFF loop, so IFF hiding no longer gates rendering.
        foreach (var grid in _grids)
        {
            var gUid = grid.Owner;
            if (gUid == ourGridId || !fixturesQuery.HasComponent(gUid))
                continue;

            var ksGridNet = EntManager.GetNetEntity(gUid);
            if (!_ksLiveContacts.Contains(ksGridNet))
                continue;

            _ksRealDrawn.Add(ksGridNet);

            EntManager.TryGetComponent<IFFComponent>(gUid, out var iff);
            var curGridToWorld = _transform.GetWorldMatrix(gUid);
            var curGridToView = curGridToWorld * worldToShuttle * shuttleToView;
            var labelColor = _shuttles.GetIFFColor(grid, self: false, iff);

            var gridAABB = curGridToWorld.TransformBox(grid.Comp.LocalAABB);

            if (!gridAABB.Intersects(viewAABB))
                continue;

            DrawGrid(handle, curGridToView, grid, labelColor);
            DrawDocks(handle, gUid, curGridToView);
        }

        // An extra marker when the controlling console sits on a different grid to the
        // shuttle, so the player can place themselves relative to it.
        if (_consoleEntity != null && xformQuery.TryGetComponent(_consoleEntity, out var consoleXform))
        {
            if (consoleXform.ParentUid != _coordinates.Value.EntityId)
            {
                var consolePositionWorld = _transform.GetWorldPosition((EntityUid)_consoleEntity);
                var p = Vector2.Transform(consolePositionWorld, worldToShuttle * shuttleToView);
                handle.DrawCircle(p, 5, Color.ToSrgb(KsHud.OffGrid), true);
            }
        }

        // Contact layer and hover tooltip on top of everything. mapPos.Position is the
        // radar's own centre in world space, used to label each contact's range.
        KsDrawContacts(handle, worldToShuttle * shuttleToView, mapPos.Position);
        KsDrawContactTooltip(handle, mapPos.Position);
    }

