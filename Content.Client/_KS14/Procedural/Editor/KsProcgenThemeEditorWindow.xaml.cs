using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared._KS14.Procedural.Editor;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._KS14.Procedural.Editor;

[GenerateTypedNameReferences]
public sealed partial class KsProcgenThemeEditorWindow : FancyWindow
{
    public event Action<int, KsProcgenThemeEditorValues>? SaveRequested;
    private readonly Dictionary<OptionButton, string[]> _choices = new();
    private int _revision;
    private bool _loaded;

    public KsProcgenThemeEditorWindow()
    {
        RobustXamlLoader.Load(this);
        Explanation.SetMessage(Loc.GetString("ks-procgen-theme-help"));
        UtilityExplanation.SetMessage(Loc.GetString("ks-procgen-theme-utilities-help"));
        Density.OnValueChanged += _ => UpdateFractions();
        Coverage.OnValueChanged += _ => UpdateFractions();
        Save.OnPressed += _ =>
        {
            Save.Disabled = true;
            SaveRequested?.Invoke(_revision, new()
            {
                Name = ThemeName.Text, TilePack = Selected(Tiles), WallPack = Selected(Walls),
                LightPack = Selected(Lights), EntityPack = Selected(Entities),
                AtmosphereProfile = Selected(Atmosphere), ElectricalProfile = Selected(Electricity),
                FurnishingDensity = Density.Value / 100f, LightingCoverage = Coverage.Value / 100f,
                CoherentContents = Coherent.Pressed, KeepCenterOpen = OpenCenter.Pressed, AllowLooseItems = LooseItems.Pressed,
            });
        };
    }

    public void ApplyState(KsProcgenThemeEditorState state)
    {
        _revision = state.Revision;
        if (!_loaded)
        {
            _loaded = true;
            ThemeName.Text = state.Values.Name;
            Fill(Tiles, state.TilePacks, state.Values.TilePack);
            Fill(Walls, state.WallPacks, state.Values.WallPack);
            Fill(Lights, state.LightPacks, state.Values.LightPack);
            Fill(Entities, state.EntityPacks, state.Values.EntityPack);
            Fill(Atmosphere, state.AtmosphereProfiles, state.Values.AtmosphereProfile);
            Fill(Electricity, state.ElectricalProfiles, state.Values.ElectricalProfile);
            Density.Value = state.Values.FurnishingDensity * 100f;
            Coverage.Value = state.Values.LightingCoverage * 100f;
            Coherent.Pressed = state.Values.CoherentContents;
            OpenCenter.Pressed = state.Values.KeepCenterOpen;
            LooseItems.Pressed = state.Values.AllowLooseItems;
        }
        // Preserve local unsaved edits on validation errors or revision conflicts.
        Save.Disabled = false;
        CatalogWarning.Visible = state.CatalogTruncated;
        Status.SetMessage(Loc.GetString(state.Status, ("detail", state.Detail)));
        if (state.Status == "ks-procgen-theme-saved") SavedKey.Text = state.Detail;
        UpdateFractions();
    }

    private void Fill(OptionButton button, string[] ids, string selected)
    {
        var choices = new[] { string.Empty }.Concat(ids).Distinct(StringComparer.Ordinal).ToList();
        if (!choices.Contains(selected)) choices.Add(selected);
        _choices[button] = choices.ToArray();
        button.Clear();
        for (var index = 0; index < choices.Count; index++)
        {
            button.AddItem(index == 0 ? Loc.GetString("ks-procgen-theme-none") : choices[index], index);
            button.SetItemMetadata(index, choices[index]);
        }
        button.SelectId(choices.IndexOf(selected));
        button.OnItemSelected += args => button.SelectId(args.Id);
    }

    private string Selected(OptionButton button) => _choices[button][button.SelectedId];

    private void UpdateFractions()
    {
        DensityLabel.Text = Loc.GetString("ks-procgen-theme-density", ("value", (int) Density.Value));
        CoverageLabel.Text = Loc.GetString("ks-procgen-theme-coverage", ("value", (int) Coverage.Value));
    }
}
