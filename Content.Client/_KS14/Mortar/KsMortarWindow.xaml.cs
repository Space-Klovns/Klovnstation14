using System.Globalization;
using Content.Client.UserInterface.Controls;
using Content.Shared._KS14.Mortar;
using Content.Shared.Localizations;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.Input;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Graphics;
using Robust.Shared.Input;
using Robust.Shared.Timing;

namespace Content.Client._KS14.Mortar;

/// <summary>
///     Shows what the server sends and raises what the player asks for. The plot and the two fields are one aim: either
///         writes the other, and only ever because the player did something, so a refresh from the server never takes away
///         what they are typing.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class KsMortarWindow : FancyWindow
{
    [Dependency] private IGameTiming _gameTiming = default!;
    [Dependency] private IInputManager _inputManager = default!;
    [Dependency] private IEntityManager _entityManager = default!;

    /// <summary>
    ///     The largest the sight's viewport is rendered, in pixels a side, however far it shows.
    /// </summary>
    private const int MaxSightPixels = 512;

    /// <summary>
    ///     Degrees and tiles a nudge button moves the aim, and with Shift held.
    /// </summary>
    public const float NudgeStep = 1f;

    public const float NudgeShiftStep = 5f;

    private static readonly Color InvalidFieldColor = Color.FromHex("#FF8080");

    /// <summary>
    ///     A compass bearing (zero is north, turning clockwise) and a distance in tiles.
    /// </summary>
    public event Action<Angle, float>? OnFire;

    /// <summary>
    ///     The aim changed to one that can be fired at, while the mortar has a sight: for its eye to follow.
    /// </summary>
    public event Action<Angle, float>? OnAim;

    private NetEntity? _sightNetEntity;
    private (double Bearing, float Distance)? _lastAim;

    private KsMortarBuiState? _state;

    /// <summary>
    ///     The fields as parsed: null while that field is not a number in its range.
    /// </summary>
    private double? _bearingDegrees;

    private float? _distance;

    public KsMortarWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        FireButton.OnPressed += _ => Fire();
        BearingEdit.OnTextChanged += _ => Validate();
        DistanceEdit.OnTextChanged += _ => Validate();
        BearingEdit.OnTextEntered += _ => Fire();
        DistanceEdit.OnTextEntered += _ => Fire();

        BearingDownButton.OnPressed += _ => NudgeBearing(-1f);
        BearingUpButton.OnPressed += _ => NudgeBearing(1f);
        DistanceDownButton.OnPressed += _ => NudgeDistance(-1f);
        DistanceUpButton.OnPressed += _ => NudgeDistance(1f);

        AimPlot.OnAimPicked += (bearing, distance) => SetAim(bearing.Degrees, distance);

        Validate();
    }

    /// <summary>
    ///     Whether both fields hold an aim that can be fired at.
    /// </summary>
    public bool InputValid => _bearingDegrees != null && _distance != null;

    public bool BearingInvalid => _bearingDegrees == null;

    public bool DistanceInvalid => _distance == null;

    public void UpdateState(KsMortarBuiState state)
    {
        var first = _state == null;
        _state = state;

        RoundsLabel.Text = Loc.GetString("ks-mortar-window-rounds", ("rounds", state.Rounds));
        RangeLabel.Text = Loc.GetString("ks-mortar-window-range", ("min", FormatNumber(state.MinRange)), ("max", FormatNumber(state.MaxRange)));

        AimPlot.SetRange(state.MinRange, state.MaxRange);
        AimPlot.Spread = float.IsFinite(state.Spread) ? state.Spread : 0f;
        AimPlot.SetImpacts(state.Impacts);
        SetSightRadius(state.SightRadius);

        // The only time code writes a field the player has not touched: something to start from, when the window opens.
        if (first && float.IsFinite(state.MinRange) && float.IsFinite(state.MaxRange))
        {
            if (BearingEdit.Text.Length == 0)
                BearingEdit.SetText(FormatNumber(0f));

            if (DistanceEdit.Text.Length == 0)
                DistanceEdit.SetText(FormatNumber(MathF.Round((state.MinRange + state.MaxRange) / 2f)));
        }

        // New limits can make what is typed fit, or not; the text stays as it is.
        Validate();
    }

    /// <summary>
    ///     Writes an aim the player picked (on the plot, or by a nudge) into both fields.
    /// </summary>
    private void SetAim(double bearingDegrees, float distance)
    {
        BearingEdit.SetText(FormatNumber((float) KsMortarAim.NormalizeDegrees(bearingDegrees)));
        DistanceEdit.SetText(FormatNumber(distance));
        Validate();
    }

    private void NudgeBearing(float direction)
    {
        var step = _inputManager.IsKeyDown(Keyboard.Key.Shift) ? NudgeShiftStep : NudgeStep;
        var from = _bearingDegrees ?? AimPlot.Bearing.Degrees;
        SetAim(from + direction * step, _distance ?? AimPlot.Distance);
    }

    private void NudgeDistance(float direction)
    {
        var step = _inputManager.IsKeyDown(Keyboard.Key.Shift) ? NudgeShiftStep : NudgeStep;
        var from = _distance ?? AimPlot.Distance;
        var distance = from + direction * step;
        if (_state != null)
            distance = Math.Clamp(distance, _state.MinRange, _state.MaxRange);

        SetAim(_bearingDegrees ?? AimPlot.Bearing.Degrees, distance);
    }

    /// <summary>
    ///     Reads both fields, marks the ones that will not do, says why, and puts the aim on the plot.
    /// </summary>
    private void Validate()
    {
        string? reason = null;

        _bearingDegrees = null;
        if (!UserInputParser.TryFloat(BearingEdit.Text.Trim(), out var bearing) || !float.IsFinite(bearing))
            reason = Loc.GetString("ks-mortar-window-bearing-not-number");
        else if (bearing < 0f || bearing > 360f)
            reason = Loc.GetString("ks-mortar-window-bearing-out-of-range");
        else
            _bearingDegrees = KsMortarAim.NormalizeDegrees(bearing);

        _distance = null;
        if (!UserInputParser.TryFloat(DistanceEdit.Text.Trim(), out var distance) || !float.IsFinite(distance))
        {
            reason ??= Loc.GetString("ks-mortar-window-distance-not-number");
        }
        else if (_state != null && (distance < _state.MinRange || distance > _state.MaxRange))
        {
            reason ??= Loc.GetString("ks-mortar-window-distance-out-of-range",
                ("min", FormatNumber(_state.MinRange)),
                ("max", FormatNumber(_state.MaxRange)));
        }
        else
        {
            _distance = distance;
        }

        BearingEdit.ModulateSelfOverride = _bearingDegrees == null ? InvalidFieldColor : null;
        DistanceEdit.ModulateSelfOverride = _distance == null ? InvalidFieldColor : null;
        ReasonLabel.Text = reason ?? " ";

        // What is valid of the aim goes on the plot; what is not keeps its last place there, greyed out.
        AimPlot.SetAim(_bearingDegrees is { } degrees ? Angle.FromDegrees(degrees) : AimPlot.Bearing, _distance ?? AimPlot.Distance);
        AimPlot.AimValid = InputValid;

        BearingReadout.Text = _bearingDegrees is { } shown
            ? Loc.GetString("ks-mortar-window-bearing-readout",
                ("degrees", ((int) Math.Round(shown) % 360).ToString("000", CultureInfo.InvariantCulture)),
                ("point", Loc.GetString($"ks-mortar-compass-{KsMortarAim.CompassPoint(shown)}")))
            : Loc.GetString("ks-mortar-window-bearing-readout-none");

        UpdateReadiness();
        RaiseAim();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        UpdateReadiness();
        UpdateSightView();
    }

    /// <summary>
    ///     The eye this player's sight shows, from the server; null while they have none.
    /// </summary>
    public void SetSightEye(NetEntity? eye)
    {
        if (_sightNetEntity == eye)
            return;

        _sightNetEntity = eye;
        UpdateSightView();
    }

    /// <summary>
    ///     Whether the sight shows a picture: once the eye the server named has arrived.
    /// </summary>
    public bool SightHasPicture => SightView.Eye != null;

    private void SetSightRadius(float sightRadius)
    {
        var enabled = float.IsFinite(sightRadius) && sightRadius > 0f;
        SightBox.Visible = enabled;
        if (!enabled)
        {
            SetSightEye(null);
            return;
        }

        SightReticle.SightRadius = sightRadius;
        SightReticle.Spread = AimPlot.Spread;

        // One pixel to a tile's thirty-second, as the main view, scaled down to fit.
        var side = Math.Clamp((int) MathF.Ceiling(sightRadius * 2f * EyeManager.PixelsPerMeter), 1, MaxSightPixels);
        if (SightView.ViewportSize != new Vector2i(side, side))
            SightView.ViewportSize = new Vector2i(side, side);
    }

    private void UpdateSightView()
    {
        // Looked up every frame: it arrives some time after the server names it, and could go before the window does.
        IEye? eye = null;
        if (_sightNetEntity is { } netEntity &&
            _entityManager.TryGetEntity(netEntity, out var eyeUid) &&
            _entityManager.TryGetComponent<EyeComponent>(eyeUid, out var eyeComponent))
        {
            eye = eyeComponent.Eye;
        }

        if (SightView.Eye != eye)
            SightView.Eye = eye;

        SightView.Visible = SightView.Eye != null;
        SightNoPicture.Visible = SightView.Eye == null;
    }

    /// <summary>
    ///     Tells the sight where the aim is now, if it moved and can be fired at.
    /// </summary>
    private void RaiseAim()
    {
        if (!SightBox.Visible || _bearingDegrees is not { } bearing || _distance is not { } distance)
            return;

        if (_lastAim is { } last && last.Bearing == bearing && last.Distance == distance)
            return;

        _lastAim = (bearing, distance);
        OnAim?.Invoke(Angle.FromDegrees(bearing), distance);
    }

    protected override void Dispose(bool disposing)
    {
        // Nothing renders through an eye whose window is gone.
        SightView.Eye = null;
        base.Dispose(disposing);
    }

    private void UpdateReadiness()
    {
        if (_state == null)
        {
            FireButton.Disabled = true;
            return;
        }

        var wait = _state.ReadyAt - _gameTiming.CurTime;
        var loaded = wait <= TimeSpan.Zero;
        FireButton.Disabled = _state.Rounds <= 0 || !loaded || !InputValid;

        ReloadBar.Value = loaded || _state.ReloadTime <= TimeSpan.Zero
            ? 1f
            : Math.Clamp(1f - (float) (wait.TotalSeconds / _state.ReloadTime.TotalSeconds), 0f, 1f);

        StatusLabel.Text = _state.Rounds <= 0
            ? Loc.GetString("ks-mortar-window-empty")
            : loaded
                ? Loc.GetString("ks-mortar-window-ready")
                : Loc.GetString("ks-mortar-window-reloading");
    }

    private void Fire()
    {
        if (FireButton.Disabled || _bearingDegrees is not { } bearing || _distance is not { } distance)
            return;

        OnFire?.Invoke(Angle.FromDegrees(bearing), distance);
    }

    private static string FormatNumber(float value)
    {
        return value.ToString("0.#", CultureInfo.InvariantCulture);
    }
}
