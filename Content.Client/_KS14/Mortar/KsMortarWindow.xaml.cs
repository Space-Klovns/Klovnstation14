using Content.Client.UserInterface.Controls;
using Content.Shared._KS14.Mortar;
using Content.Shared.Localizations;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client._KS14.Mortar;

/// <summary>
///     Shows what the server sends and raises what the player asks for. The inputs are only ever written by the player, so a
///         refresh never takes away what they are typing.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class KsMortarWindow : FancyWindow
{
    [Dependency] private IGameTiming _gameTiming = default!;

    /// <summary>
    ///     A compass bearing (zero is north, turning clockwise) and a distance in tiles.
    /// </summary>
    public event Action<Angle, float>? OnFire;

    private KsMortarBuiState? _state;
    private bool _invalid;

    public KsMortarWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        FireButton.OnPressed += _ => Fire();
    }

    public void UpdateState(KsMortarBuiState state)
    {
        _state = state;
        _invalid = false;

        RoundsLabel.Text = Loc.GetString("ks-mortar-window-rounds", ("rounds", state.Rounds));
        RangeLabel.Text = Loc.GetString("ks-mortar-window-range", ("min", (int) MathF.Round(state.MinRange)), ("max", (int) MathF.Round(state.MaxRange)));

        if (DistanceEdit.Text.Length == 0 && float.IsFinite(state.MinRange) && float.IsFinite(state.MaxRange))
            DistanceEdit.Text = ((int) MathF.Round((state.MinRange + state.MaxRange) / 2f)).ToString();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (_state == null)
            return;

        var wait = _state.ReadyAt - _gameTiming.CurTime;
        var ready = _state.Rounds > 0 && wait <= TimeSpan.Zero;
        FireButton.Disabled = !ready;

        StatusLabel.Text = _invalid
            ? Loc.GetString("ks-mortar-window-invalid")
            : _state.Rounds <= 0
                ? Loc.GetString("ks-mortar-window-empty")
                : ready
                    ? Loc.GetString("ks-mortar-window-ready")
                    : Loc.GetString("ks-mortar-window-reloading", ("seconds", (int) Math.Ceiling(wait.TotalSeconds)));
    }

    private void Fire()
    {
        if (!UserInputParser.TryFloat(BearingEdit.Text.Trim(), out var bearing) || !float.IsFinite(bearing) ||
            !UserInputParser.TryFloat(DistanceEdit.Text.Trim(), out var distance) || !float.IsFinite(distance))
        {
            _invalid = true;
            return;
        }

        _invalid = false;
        OnFire?.Invoke(Angle.FromDegrees(bearing), distance);
    }
}
