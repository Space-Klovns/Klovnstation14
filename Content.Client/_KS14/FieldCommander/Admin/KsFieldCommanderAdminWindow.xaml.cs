/// <summary>
///     The field commander admin window. It only shows what it is given and raises what the admin asks for: the
///         EUI sends it. The status strip is rewritten on every refresh; the tabs' inputs follow the server only while
///         the admin has not typed over them, so a refresh never takes away an unapplied edit.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class KsFieldCommanderAdminWindow : FancyWindow
{
    private const int PhasesTab = 0;
    private const int AssetsTab = 1;
    private const int CustomWaveTab = 2;
    private const int QueueTab = 3;

    /// <summary>
    ///     A change for the server, already naming the commander shown.
    /// </summary>
    public event Action<KsFieldCommanderAdminEuiMessage>? OnAdminMessage;

    private NetEntity? _rule;
    private NetEntity? _refreshRequestedFor;
    private bool _hasState;
    private bool _paused;
    private int _currentPhase = -1;
    private KsFieldCommanderAdminEuiState? _state;

    /// <summary>
    ///     The last full state shown, for tests.
    /// </summary>
    public KsFieldCommanderAdminEuiState? State => _state;

    private readonly List<PhaseRow> _phaseRows = new();
    private readonly List<AssetRow> _assetRows = new();
    private readonly List<WaveRow> _waveRows = new();

    public KsFieldCommanderAdminWindow()
    {
        RobustXamlLoader.Load(this);

        Tabs.SetTabTitle(PhasesTab, Loc.GetString("ks-fieldcommander-admin-tab-phases"));
        Tabs.SetTabTitle(AssetsTab, Loc.GetString("ks-fieldcommander-admin-tab-assets"));
        Tabs.SetTabTitle(CustomWaveTab, Loc.GetString("ks-fieldcommander-admin-tab-custom-wave"));
        Tabs.SetTabTitle(QueueTab, Loc.GetString("ks-fieldcommander-admin-tab-queue"));

        PauseButton.OnPressed += _ => Send(rule => new KsFieldCommanderAdminSetPausedMessage(rule, !_paused));
        ForceWaveButton.OnPressed += _ => Send(rule => new KsFieldCommanderAdminForceWaveMessage(rule));
        RefreshButton.OnPressed += _ => RequestRefresh();
        AddAssetButton.OnPressed += _ => AddAsset();
        AddWaveRowButton.OnPressed += _ => AddWaveRow();
        QueueWaveButton.OnPressed += _ => SendWave(sendNow: false);
        SendWaveButton.OnPressed += _ => SendWave(sendNow: true);

        ClearRows();
        AddWaveRow();
        ApplyStatus(new KsFieldCommanderAdminStatusData());
    }

    #region State

    /// <summary>
    ///     Everything the tabs show, sent when the window opens and after every change made through it.
    /// </summary>
    public void UpdateState(KsFieldCommanderAdminEuiState state)
    {
        if (state.Rule != _rule || !_hasState)
        {
            // Another commander: nothing typed for the last one applies.
            _rule = state.Rule;
            ClearRows();
            foreach (var waveRow in _waveRows)
                waveRow.Root.Orphan();

            _waveRows.Clear();
            AddWaveRow();
        }

        _hasState = true;
        _state = state;
        _refreshRequestedFor = null;

        var hasRule = state.Rule != null;
        NoRuleLabel.Visible = !hasRule;
        StatusPanel.Visible = hasRule;
        Tabs.Visible = hasRule;

        ApplyStatus(state.Status);

        for (var i = 0; i < state.Phases.Count; i++)
        {
            if (i >= _phaseRows.Count)
                _phaseRows.Add(new PhaseRow(this, i));

            _phaseRows[i].Update(state.Phases[i], state);
        }

        for (var i = 0; i < state.Assets.Count; i++)
        {
            if (i >= _assetRows.Count)
                _assetRows.Add(new AssetRow(this, i, state.DeliveryNames));

            _assetRows[i].Update(state.Assets[i], state);
        }

        foreach (var waveRow in _waveRows)
            waveRow.UpdateOptions(state);

        UpdatePhaseMarkers();
    }

    /// <summary>
    ///     The status strip's own refresh; touches nothing else.
    /// </summary>
    public void UpdateStatus(NetEntity? rule, KsFieldCommanderAdminStatusData status)
    {
        if (_hasState && rule != _rule)
        {
            // The commander ended, or another started: the tabs need the whole state, once.
            if (_refreshRequestedFor != rule)
            {
                _refreshRequestedFor = rule;
                RequestRefresh();
            }

            return;
        }

        ApplyStatus(status);
        UpdatePhaseMarkers();
    }

    public void ShowResult(bool accepted)
    {
        ResultLabel.Text = Loc.GetString(accepted
            ? "ks-fieldcommander-admin-result-accepted"
            : "ks-fieldcommander-admin-result-refused");
    }

    private void ShowInvalid()
    {
        ResultLabel.Text = Loc.GetString("ks-fieldcommander-admin-result-invalid");
    }

    private void ApplyStatus(KsFieldCommanderAdminStatusData status)
    {
        _paused = status.Paused;
        _currentPhase = status.PhaseIndex;

        PhaseLabel.Text = status.PhaseName is { } phaseName
            ? Loc.GetString("ks-fieldcommander-admin-status-phase", ("index", status.PhaseIndex), ("phase", Loc.GetString(phaseName)))
            : Loc.GetString("ks-fieldcommander-admin-status-phase-none");
        DoctrineLabel.Text = status.DoctrineName is { } doctrineName
            ? Loc.GetString("ks-fieldcommander-admin-status-doctrine", ("doctrine", Loc.GetString(doctrineName)))
            : Loc.GetString("ks-fieldcommander-admin-status-doctrine-none");
        NextWaveLabel.Text = status.NextWaveIn is { } nextWaveIn
            ? Loc.GetString("ks-fieldcommander-admin-status-next-wave", ("seconds", Seconds(nextWaveIn)))
            : Loc.GetString("ks-fieldcommander-admin-status-next-wave-none");
        NextPhaseLabel.Text = status.NextPhaseIn is { } nextPhaseIn
            ? Loc.GetString("ks-fieldcommander-admin-status-next-phase", ("seconds", Seconds(nextPhaseIn)))
            : Loc.GetString("ks-fieldcommander-admin-status-next-phase-none");
        AliveLabel.Text = Loc.GetString("ks-fieldcommander-admin-status-alive", ("alive", status.Alive), ("cap", status.Cap));
        DefendersLabel.Text = Loc.GetString("ks-fieldcommander-admin-status-defenders", ("defenders", status.Defenders));
        BudgetLabel.Text = Loc.GetString("ks-fieldcommander-admin-status-budget", ("budget", Format(status.CarriedBudget)));
        WavesLabel.Text = Loc.GetString("ks-fieldcommander-admin-status-waves", ("waves", status.WavesSent), ("queued", status.QueuedWaves.Count));

        PausedLabel.Text = Loc.GetString("ks-fieldcommander-admin-status-paused", ("paused", status.Paused));
        PausedLabel.FontColorOverride = status.Paused ? Color.Orange : null;
        PauseButton.Text = Loc.GetString(status.Paused ? "ks-fieldcommander-admin-unpause" : "ks-fieldcommander-admin-pause");

        RebuildQueue(status);
    }

    private void RebuildQueue(KsFieldCommanderAdminStatusData status)
    {
        QueueList.RemoveAllChildren();
        if (status.QueuedWaves.Count == 0)
        {
            QueueList.AddChild(new Label { Text = Loc.GetString("ks-fieldcommander-admin-queue-empty"), StyleClasses = { "LabelWeak" } });
            return;
        }

        for (var i = 0; i < status.QueuedWaves.Count; i++)
        {
            var wave = status.QueuedWaves[i];
            var purchases = string.Join(Loc.GetString("ks-fieldcommander-admin-list-separator"),
                wave.Purchases.Select(purchase => Loc.GetString("ks-fieldcommander-admin-queue-purchase",
                    ("count", purchase.Count),
                    ("index", purchase.Asset),
                    ("name", AssetName(purchase.Asset)))));

            QueueList.AddChild(new Label
            {
                Text = Loc.GetString("ks-fieldcommander-admin-queue-wave", ("position", i + 1), ("purchases", purchases)),
            });

            if (wave.Announcement is { } announcement)
            {
                QueueList.AddChild(new Label
                {
                    Text = Loc.GetString("ks-fieldcommander-admin-queue-announcement", ("text", announcement)),
                    StyleClasses = { "LabelWeak" },
                    Margin = new Thickness(16, 0, 0, 0),
                });
            }
        }
    }

    private void UpdatePhaseMarkers()
    {
        foreach (var row in _phaseRows)
            row.SetCurrent(row.Index == _currentPhase);
    }

    private void ClearRows()
    {
        _phaseRows.Clear();
        PhasesGrid.RemoveAllChildren();
        foreach (var header in new[] { "index", "name", "start", "interval", "budget", "apply", "go" })
            PhasesGrid.AddChild(Header($"ks-fieldcommander-admin-phase-header-{header}"));

        _assetRows.Clear();
        AssetsGrid.RemoveAllChildren();
        foreach (var header in new[] { "index", "entity", "humanoid", "count", "cost", "weight", "min-phase", "max-alive", "delivery", "living", "notes", "actions" })
            AssetsGrid.AddChild(Header($"ks-fieldcommander-admin-asset-header-{header}"));
    }

    private static Label Header(string locId)
    {
        return new Label { Text = Loc.GetString(locId), StyleClasses = { "LabelSubText" } };
    }

    #endregion

    #region Sending

    private void Send(Func<NetEntity, KsFieldCommanderAdminEuiMessage> make)
    {
        if (_rule is { } rule)
            OnAdminMessage?.Invoke(make(rule));
    }

    private void RequestRefresh()
    {
        // The server answers a refresh with the commander it now shows, whatever this one names.
        OnAdminMessage?.Invoke(new KsFieldCommanderAdminRefreshMessage(_rule ?? NetEntity.Invalid));
    }

    private void AddAsset()
    {
        var entity = AddAssetEntity.Text.Trim();
        if (entity.Length == 0)
        {
            ShowInvalid();
            return;
        }

        Send(rule => new KsFieldCommanderAdminAddAssetMessage(rule, new KsFieldCommanderAdminAssetValues(Entity: entity)));
        AddAssetEntity.Text = string.Empty;
    }

    private void AddWaveRow()
    {
        var row = new WaveRow(this);
        _waveRows.Add(row);
        WaveRows.AddChild(row.Root);
        if (_state != null)
            row.UpdateOptions(_state);
    }

    private void RemoveWaveRow(WaveRow row)
    {
        row.Root.Orphan();
        _waveRows.Remove(row);
    }

    private void SendWave(bool sendNow)
    {
        var purchases = new List<KsFieldCommanderAdminPurchase>();
        foreach (var row in _waveRows)
        {
            if (row.Asset is not { } asset)
                continue;

            if (!int.TryParse(row.Count.Text.Trim(), out var count))
            {
                ShowInvalid();
                return;
            }

            purchases.Add(new KsFieldCommanderAdminPurchase(asset, count));
        }

        if (purchases.Count == 0)
        {
            ShowInvalid();
            return;
        }

        var announcement = WaveAnnouncement.Text.Trim();
        Send(rule => new KsFieldCommanderAdminQueueWaveMessage(rule, purchases, announcement.Length > 0 ? announcement : null, sendNow));
    }

    #endregion

    #region Formatting

    private string AssetName(int index)
    {
        if (_state == null || index < 0 || index >= _state.Assets.Count)
            return "?";

        var asset = _state.Assets[index];
        return asset.Humanoid ?? asset.Entity ?? "?";
    }

    private static int Seconds(TimeSpan time)
    {
        return (int)Math.Ceiling(time.TotalSeconds);
    }

    private static string Format(float value)
    {
        return value.ToString("0.###", CultureInfo.InvariantCulture);
    }

    private static string Format(TimeSpan time)
    {
        return time.TotalSeconds.ToString("0.###", CultureInfo.InvariantCulture);
    }

    private static bool TryParseSeconds(string text, TimeSpan max, out TimeSpan time)
    {
        time = TimeSpan.Zero;
        if (!UserInputParser.TryDouble(text.Trim(), out var seconds) || !double.IsFinite(seconds))
            return false;

        // The server clamps too; this only keeps the conversion from overflowing.
        time = TimeSpan.FromSeconds(Math.Clamp(seconds, 0d, max.TotalSeconds));
        return true;
    }

    private static bool TryParseFloat(string text, out float value)
    {
        return UserInputParser.TryFloat(text.Trim(), out value) && float.IsFinite(value);
    }

