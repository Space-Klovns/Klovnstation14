    #region Rows

    /// <summary>
    ///     A text input that follows the server's value until the admin types over it, and again once their change
    ///         has been sent.
    /// </summary>
    private sealed class EditField
    {
        public readonly LineEdit Edit;
        private string _serverText = string.Empty;
        private bool _takeNext = true;

        public EditField(float minWidth)
        {
            Edit = new LineEdit { MinWidth = minWidth };
        }

        public bool Edited => Edit.Text != _serverText;

        public string Text => Edit.Text;

        public void SetServer(string text)
        {
            if (_takeNext || !Edited)
                Edit.Text = text;

            _serverText = text;
            _takeNext = false;
        }

        /// <summary>
        ///     The admin's value has gone to the server: whatever it answers is shown, kept or clamped or refused.
        /// </summary>
        public void Sent()
        {
            _takeNext = true;
        }
    }

    private sealed class PhaseRow
    {
        public readonly int Index;
        private readonly KsFieldCommanderAdminWindow _window;
        private readonly Label _indexLabel;
        private readonly Label _nameLabel;
        private readonly EditField _start = new(80);
        private readonly EditField _interval = new(80);
        private readonly EditField _budget = new(80);
        private TimeSpan _maxTime;

        public PhaseRow(KsFieldCommanderAdminWindow window, int index)
        {
            _window = window;
            Index = index;
            _indexLabel = new Label { Text = index.ToString() };
            _nameLabel = new Label { MinWidth = 140 };

            var apply = new Button { Text = Loc.GetString("ks-fieldcommander-admin-apply") };
            apply.OnPressed += _ => Apply();
            var go = new Button { Text = Loc.GetString("ks-fieldcommander-admin-phase-go") };
            go.OnPressed += _ => _window.Send(rule => new KsFieldCommanderAdminSetPhaseMessage(rule, Index));

            var grid = window.PhasesGrid;
            grid.AddChild(_indexLabel);
            grid.AddChild(_nameLabel);
            grid.AddChild(_start.Edit);
            grid.AddChild(_interval.Edit);
            grid.AddChild(_budget.Edit);
            grid.AddChild(apply);
            grid.AddChild(go);
        }

        public void Update(KsFieldCommanderAdminPhaseData phase, KsFieldCommanderAdminEuiState state)
        {
            _maxTime = state.MaxTime;
            _nameLabel.Text = Loc.GetString(phase.Name);
            _start.SetServer(Format(phase.Start));
            _interval.SetServer(Format(phase.WaveInterval));
            _budget.SetServer(Format(phase.Budget));
        }

        public void SetCurrent(bool current)
        {
            _indexLabel.Text = current ? Loc.GetString("ks-fieldcommander-admin-phase-current", ("index", Index)) : Index.ToString();
            _indexLabel.FontColorOverride = current ? Color.LightGreen : null;
        }

        private void Apply()
        {
            TimeSpan? start = null;
            TimeSpan? interval = null;
            float? budget = null;

            if (_start.Edited)
            {
                if (!TryParseSeconds(_start.Text, _maxTime, out var value))
                {
                    _window.ShowInvalid();
                    return;
                }

                start = value;
            }

            if (_interval.Edited)
            {
                if (!TryParseSeconds(_interval.Text, _maxTime, out var value))
                {
                    _window.ShowInvalid();
                    return;
                }

                interval = value;
            }

            if (_budget.Edited)
            {
                if (!TryParseFloat(_budget.Text, out var value))
                {
                    _window.ShowInvalid();
                    return;
                }

                budget = value;
            }

            _start.Sent();
            _interval.Sent();
            _budget.Sent();
            _window.Send(rule => new KsFieldCommanderAdminEditPhaseMessage(rule, Index, start, interval, budget));
        }
    }

    private sealed class AssetRow
    {
        private readonly int _index;
        private readonly KsFieldCommanderAdminWindow _window;
        private readonly Label _indexLabel;
        private readonly EditField _entity = new(200);
        private readonly EditField _humanoid = new(230);
        private readonly EditField _count = new(45);
        private readonly EditField _cost = new(55);
        private readonly EditField _weight = new(55);
        private readonly EditField _minPhase = new(45);
        private readonly EditField _maxAlive = new(45);
        private readonly OptionButton _delivery = new();
        private readonly Label _living = new();
        private readonly Label _notes = new() { StyleClasses = { "LabelWeak" } };
        private readonly Button _toggle = new();
        private byte _serverDelivery;
        private bool _takeDelivery = true;
        private bool _disabled;

        public AssetRow(KsFieldCommanderAdminWindow window, int index, List<string> deliveryNames)
        {
            _window = window;
            _index = index;
            _indexLabel = new Label { Text = index.ToString() };

            for (var i = 0; i < deliveryNames.Count; i++)
            {
                var name = deliveryNames[i];
                var locId = $"ks-fieldcommander-admin-delivery-{name.ToLowerInvariant()}";
                _delivery.AddItem(Loc.TryGetString(locId, out var label) ? label : name, i);
            }

            _delivery.OnItemSelected += args => _delivery.SelectId(args.Id);

            var apply = new Button { Text = Loc.GetString("ks-fieldcommander-admin-apply") };
            apply.OnPressed += _ => Apply();
            _toggle.OnPressed += _ => _window.Send(rule => new KsFieldCommanderAdminSetAssetDisabledMessage(rule, _index, !_disabled));

            var actions = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 4 };
            actions.AddChild(apply);
            actions.AddChild(_toggle);

            var grid = window.AssetsGrid;
            grid.AddChild(_indexLabel);
            grid.AddChild(_entity.Edit);
            grid.AddChild(_humanoid.Edit);
            grid.AddChild(_count.Edit);
            grid.AddChild(_cost.Edit);
            grid.AddChild(_weight.Edit);
            grid.AddChild(_minPhase.Edit);
            grid.AddChild(_maxAlive.Edit);
            grid.AddChild(_delivery);
            grid.AddChild(_living);
            grid.AddChild(_notes);
            grid.AddChild(actions);
        }

        public void Update(KsFieldCommanderAdminAssetData asset, KsFieldCommanderAdminEuiState state)
        {
            _entity.SetServer(asset.Entity ?? string.Empty);
            _humanoid.SetServer(asset.Humanoid ?? string.Empty);
            _count.SetServer(asset.Count.ToString());
            _cost.SetServer(Format(asset.Cost));
            _weight.SetServer(Format(asset.Weight));
            _minPhase.SetServer(asset.MinPhase.ToString());
            _maxAlive.SetServer(asset.MaxAlive.ToString());

            if (_takeDelivery || _delivery.SelectedId == _serverDelivery)
                _delivery.TrySelectId(asset.Delivery);

            _serverDelivery = asset.Delivery;
            _takeDelivery = false;

            _living.Text = asset.Living.ToString();
            _notes.Text = Loc.GetString("ks-fieldcommander-admin-asset-notes",
                ("hasTags", asset.Tags.Count > 0),
                ("tags", string.Join(", ", asset.Tags.OrderBy(tag => tag))),
                ("every", asset.GuaranteedEveryWaves),
                ("onPhase", asset.GuaranteedOnPhaseEnter),
                ("disabled", asset.Disabled));

            _disabled = asset.Disabled;
            _toggle.Text = Loc.GetString(asset.Disabled ? "ks-fieldcommander-admin-asset-enable" : "ks-fieldcommander-admin-asset-disable");
            _indexLabel.FontColorOverride = asset.Disabled ? Color.Gray : null;
            _entity.Edit.ModulateSelfOverride = asset.Disabled ? Color.Gray : null;
        }

        private void Apply()
        {
            int? count = null, minPhase = null, maxAlive = null;
            float? cost = null, weight = null;

            if (!TryInt(_count, ref count) ||
                !TryInt(_minPhase, ref minPhase) ||
                !TryInt(_maxAlive, ref maxAlive) ||
                !TryFloat(_cost, ref cost) ||
                !TryFloat(_weight, ref weight))
            {
                _window.ShowInvalid();
                return;
            }

            // Sent together: the server sets the one and clears the other.
            string? entity = null, humanoid = null;
            if (_entity.Edited || _humanoid.Edited)
            {
                entity = _entity.Text.Trim();
                humanoid = _humanoid.Text.Trim();
                if (entity.Length == 0 && humanoid.Length == 0)
                {
                    _window.ShowInvalid();
                    return;
                }
            }

            byte? delivery = _delivery.SelectedId != _serverDelivery ? (byte)_delivery.SelectedId : null;

            foreach (var field in new[] { _entity, _humanoid, _count, _cost, _weight, _minPhase, _maxAlive })
                field.Sent();

            _takeDelivery = true;

            var values = new KsFieldCommanderAdminAssetValues(
                Entity: string.IsNullOrEmpty(entity) ? null : entity,
                Humanoid: string.IsNullOrEmpty(humanoid) ? null : humanoid,
                Count: count,
                Cost: cost,
                Weight: weight,
                MinPhase: minPhase,
                MaxAlive: maxAlive,
                Delivery: delivery);

            _window.Send(rule => new KsFieldCommanderAdminEditAssetMessage(rule, _index, values));
        }

        private static bool TryInt(EditField field, ref int? value)
        {
            if (!field.Edited)
                return true;

            if (!int.TryParse(field.Text.Trim(), out var parsed))
                return false;

            value = parsed;
            return true;
        }

        private static bool TryFloat(EditField field, ref float? value)
        {
            if (!field.Edited)
                return true;

            if (!TryParseFloat(field.Text, out var parsed))
                return false;

            value = parsed;
            return true;
        }
    }

    private sealed class WaveRow
    {
        public readonly BoxContainer Root = new() { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 6 };
        public readonly LineEdit Count = new() { Text = "1", MinWidth = 60 };
        private readonly OptionButton _asset = new() { MinWidth = 320 };
        private bool _hasOptions;

        public WaveRow(KsFieldCommanderAdminWindow window)
        {
            _asset.OnItemSelected += args => _asset.SelectId(args.Id);

            var remove = new Button { Text = Loc.GetString("ks-fieldcommander-admin-wave-remove-row") };
            remove.OnPressed += _ => window.RemoveWaveRow(this);

            Root.AddChild(new Label { Text = Loc.GetString("ks-fieldcommander-admin-wave-asset"), VerticalAlignment = VAlignment.Center });
            Root.AddChild(_asset);
            Root.AddChild(new Label { Text = Loc.GetString("ks-fieldcommander-admin-wave-count"), VerticalAlignment = VAlignment.Center });
            Root.AddChild(Count);
            Root.AddChild(remove);
        }

        /// <summary>
        ///     The asset picked, if there is one to pick.
        /// </summary>
        public int? Asset => _hasOptions ? _asset.SelectedId : null;

        /// <summary>
        ///     Lists the assets that can be sent, keeping the one picked while it can still be.
        /// </summary>
        public void UpdateOptions(KsFieldCommanderAdminEuiState state)
        {
            var selected = _hasOptions ? _asset.SelectedId : (int?)null;
            _asset.Clear();
            _hasOptions = false;

            for (var i = 0; i < state.Assets.Count; i++)
            {
                var asset = state.Assets[i];
                if (asset.Disabled)
                    continue;

                _asset.AddItem(Loc.GetString("ks-fieldcommander-admin-wave-option",
                    ("index", i),
                    ("name", asset.Humanoid ?? asset.Entity ?? "?"),
                    ("count", asset.Count),
                    ("cost", Format(asset.Cost))), i);
                _hasOptions = true;
            }

            if (selected is { } id)
                _asset.TrySelectId(id);
        }
    }

