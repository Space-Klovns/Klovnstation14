using System.Numerics;
using Content.Client._KS14.Shuttles.UI;
using Content.Client.Resources;
using Content.Shared.Nuke;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._KS14.Nuke.UI;

/// <summary>
///     Retro control panel for the nuclear fission explosive, after /tg/'s NuclearBomb UI:
///     two green-on-black readouts, a chunky keypad and big ARM / ANCHOR keys.
///     Exposes the same API as the upstream NukeMenu so <c>NukeBoundUserInterface</c> can use either.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class KsNukeMenu : KsBaseWindow
{
    private const string DisplayFontPath = "/Fonts/RobotoMono/RobotoMono-Regular.ttf";
    private const string TitleFontPath = "/Fonts/RobotoMono/RobotoMono-Bold.ttf";

    private static readonly Color Casing = Color.FromHex("#E8E4C9");
    private static readonly Color CasingHighlight = Color.FromHex("#FFFFFF");
    private static readonly Color CasingShadow = Color.FromHex("#8C8875");
    private static readonly Color TitleBackground = Color.FromHex("#D3CFB7");
    private static readonly Color Ink = Color.FromHex("#2F2E26");
    private static readonly Color DisplayBackground = Color.FromHex("#000000");
    private static readonly Color DisplayText = Color.FromHex("#2BE84A");
    private static readonly Color FrameColor = Color.FromHex("#000000");

    [Dependency] private IResourceCache _resourceCache = default!;

    public event Action<int>? OnKeypadButtonPressed;
    public event Action? OnClearButtonPressed;
    public event Action? OnEnterButtonPressed;

    public KsNukeMenu()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        Bezel.PanelOverride = new KsBevelStyleBox
        {
            Face = Casing,
            Highlight = CasingHighlight,
            Shadow = CasingShadow,
        };
        TitleBar.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = TitleBackground,
            BorderColor = CasingShadow,
            BorderThickness = new Thickness(0, 0, 0, 2),
        };
        TitleLabel.FontOverride = _resourceCache.GetFont(TitleFontPath, 12);
        TitleLabel.FontColorOverride = Ink;
        CloseButton.FontSize = 11;
        CloseButton.OnPressed += _ => Close();

        var displayFont = _resourceCache.GetFont(DisplayFontPath, 17);
        FirstDisplay.PanelOverride = DisplayBox();
        SecondDisplay.PanelOverride = DisplayBox();
        foreach (var label in new[] { FirstStatusLabel, SecondStatusLabel })
        {
            label.FontOverride = displayFont;
            label.FontColorOverride = DisplayText;
        }

        EjectFrame.PanelOverride = FrameBox();
        KeypadFrame.PanelOverride = FrameBox();
        CommandFrame.PanelOverride = FrameBox();

        FillKeypadGrid();
    }

    /// <summary>
    ///     Fill keypad buttons in keypad grid
    /// </summary>
    private void FillKeypadGrid()
    {
        for (var i = 1; i <= 9; i++)
        {
            AddKeypadButton(i);
        }

        AddKey("C", KsNukeKeyColor.Yellow).OnPressed += _ => OnClearButtonPressed?.Invoke();
        AddKeypadButton(0);
        AddKey("E", KsNukeKeyColor.Orange).OnPressed += _ => OnEnterButtonPressed?.Invoke();
    }

    private void AddKeypadButton(int i)
    {
        AddKey(i.ToString(), KsNukeKeyColor.Beige).OnPressed += _ => OnKeypadButtonPressed?.Invoke(i);
    }

    private KsNukeKeyButton AddKey(string text, KsNukeKeyColor color)
    {
        var key = new KsNukeKeyButton
        {
            Text = text,
            KeyColor = color,
            FontSize = 28,
            SetSize = new Vector2(55, 50),
        };
        KeypadGrid.AddChild(key);
        return key;
    }

    public void UpdateState(NukeUiState state)
    {
        string firstMsg, secondMsg;

        ArmButton.Text = Loc.GetString("nuke-user-interface-arm-button");

        switch (state.Status)
        {
            case NukeStatus.AWAIT_DISK:
                firstMsg = Loc.GetString("nuke-user-interface-first-status-device-locked");
                secondMsg = Loc.GetString("nuke-user-interface-second-status-await-disk");
                break;
            case NukeStatus.AWAIT_CODE:
                firstMsg = Loc.GetString("nuke-user-interface-first-status-input-code");
                secondMsg = Loc.GetString("nuke-user-interface-second-status-current-code",
                    ("code", VisualizeCode(state.EnteredCodeLength, state.MaxCodeLength)));
                break;
            case NukeStatus.AWAIT_ARM:
                firstMsg = Loc.GetString("nuke-user-interface-first-status-device-ready");
                secondMsg = Loc.GetString("nuke-user-interface-second-status-time",
                    ("time", state.RemainingTime));
                break;
            case NukeStatus.ARMED:
                firstMsg = Loc.GetString("nuke-user-interface-first-status-device-armed");
                secondMsg = Loc.GetString("nuke-user-interface-second-status-time",
                    ("time", state.RemainingTime));
                ArmButton.Text = Loc.GetString("nuke-user-interface-disarm-button");
                break;
            case NukeStatus.COOLDOWN:
                firstMsg = Loc.GetString("nuke-user-interface-first-status-device-cooldown");
                secondMsg = Loc.GetString("nuke-user-interface-second-status-cooldown-time",
                    ("time", state.CooldownTime));
                break;
            default:
                // shouldn't normally be here
                firstMsg = Loc.GetString("nuke-user-interface-status-error");
                secondMsg = Loc.GetString("nuke-user-interface-status-error");
                break;
        }

        FirstStatusLabel.Text = firstMsg;
        SecondStatusLabel.Text = secondMsg;

        EjectButton.Disabled = !state.DiskInserted || state.Status == NukeStatus.ARMED || !state.IsAnchored;
        EjectGlyph.Modulate = EjectButton.Disabled ? Color.White.WithAlpha(0.4f) : Color.White;
        AnchorButton.Disabled = state.Status == NukeStatus.ARMED;
        AnchorButton.Pressed = state.IsAnchored;
        ArmButton.Disabled = !state.AllowArm || !state.IsAnchored;
    }

    private static string VisualizeCode(int codeLength, int maxLength)
    {
        return new string('*', codeLength) + new string('_', maxLength - codeLength);
    }

    protected override DragMode GetDragModeFor(Vector2 relativeMousePos)
    {
        return DragMode.Move;
    }

    /// <summary>
    ///     A sunken black readout window.
    /// </summary>
    private static KsBevelStyleBox DisplayBox()
    {
        return new KsBevelStyleBox
        {
            Face = DisplayBackground,
            Highlight = CasingShadow,
            Shadow = CasingHighlight,
            ContentMarginLeftOverride = 9,
            ContentMarginRightOverride = 9,
            ContentMarginTopOverride = 6,
            ContentMarginBottomOverride = 6,
        };
    }

    /// <summary>
    ///     The black surround that keys sit in.
    /// </summary>
    private static StyleBoxFlat FrameBox()
    {
        return new StyleBoxFlat
        {
            BackgroundColor = FrameColor,
            ContentMarginLeftOverride = 3,
            ContentMarginRightOverride = 3,
            ContentMarginTopOverride = 3,
            ContentMarginBottomOverride = 3,
        };
    }
}
