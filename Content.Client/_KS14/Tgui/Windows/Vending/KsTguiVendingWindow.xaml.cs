namespace Content.Client._KS14.Tgui.Windows.Vending;

/// <summary>
///     The vending machine window laid out after tgui's <c>Vending.tsx</c>: the user card, the machine's flavour text as
///         its ad, the products as a grid or a list with a search box, and a button per category at the bottom. SS14
///         has no prices or credits, so tgui's balance and price tags are left out.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class KsTguiVendingWindow : FancyWindow
{
    [Dependency] private IEntityManager _entityManager = default!;
    [Dependency] private IPrototypeManager _prototypeManager = default!;
    [Dependency] private IPlayerManager _playerManager = default!;
    [Dependency] private ContentLocalizationManager _contentLocalizationManager = default!;

    private readonly LineEdit _searchBar;
    private readonly KsTguiButton _layoutToggle;
    private readonly BoxContainer _productsBody;
    private readonly Label _outOfStockLabel;

    private List<VendingMachineInventoryEntry> _inventory = new();
    private readonly Dictionary<(InventoryType Type, string Id), KsTguiVendingEntry> _entries = new();
    private InventoryType _selectedCategory = InventoryType.Regular;
    private bool _enabled;
    private bool _gridLayout = true;

    /// <summary>
    ///     The player clicked a product.
    /// </summary>
    public event Action<InventoryType, string>? OnVend;

    public KsTguiVendingWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _searchBar = new LineEdit
        {
            PlaceHolder = Loc.GetString("vending-machine-component-search-filter"),
            MinWidth = 120f,
        };
        _searchBar.OnTextChanged += _ => Rebuild();

        _layoutToggle = new KsTguiButton { Icon = KsTguiIcons.ThList, Compact = true };
        _layoutToggle.OnPressed += _ =>
        {
            _gridLayout = !_gridLayout;
            Rebuild();
        };

        var buttons = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 6 };
        buttons.AddChild(_searchBar);
        buttons.AddChild(_layoutToggle);

        ProductsSection.Title = Loc.GetString("ks-tgui-vending-products");
        ProductsSection.Buttons = buttons;

        _productsBody = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, HorizontalExpand = true };
        ProductsSection.AddChild(_productsBody);

        _outOfStockLabel = new Label
        {
            Text = Loc.GetString("vending-machine-component-try-eject-out-of-stock"),
            HorizontalAlignment = HAlignment.Center,
        };

        RefreshUserNotice();

        // The machine's own flavour text is the closest thing SS14 has to tg's advert.
        AdNotice.Text = $"{Loc.GetString("vending-machine-flavor-left")} ({Loc.GetString("vending-machine-flavor-right")})";
    }

    private void RefreshUserNotice()
    {
        UserNotice.RemoveAllChildren();

        var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 6 };
        row.AddChild(new KsTguiIcon { Glyph = KsTguiIcons.IdCard, IconSize = 1.5f });

        var label = new RichTextLabel { VerticalAlignment = VAlignment.Center };
        label.AddStyleClass(KsTguiNoticeBox.StyleClassNoticeText);
        var name = _playerManager.LocalEntity is { } userUid ? Identity.Name(userUid, _entityManager) : string.Empty;
        label.SetMessage(FormattedMessage.FromUnformatted(name), Color.White);
        row.AddChild(label);

        UserNotice.AddChild(row);
    }

    /// <summary>
    ///     Replaces the whole inventory.
    /// </summary>
    public void Populate(List<VendingMachineInventoryEntry> inventory, bool enabled)
    {
        _inventory = inventory;
        _enabled = enabled;
        Rebuild();
    }

    /// <summary>
    ///     Refreshes the stock counts and what can be bought in place.
    /// </summary>
    public void UpdateAmounts(List<VendingMachineInventoryEntry> inventory, bool enabled)
    {
        _inventory = inventory;
        _enabled = enabled;

        foreach (var entry in inventory)
        {
            if (_entries.TryGetValue((entry.Type, entry.ID), out var cell))
                cell.SetStock(entry.Amount, enabled);
        }
    }

    private bool Searching => _searchBar.Text.Length >= 2;

    private void Rebuild()
    {
        _productsBody.RemoveAllChildren();
        _entries.Clear();

        if (_inventory.Count == 0)
        {
            _productsBody.AddChild(_outOfStockLabel);
            CategorySection.Visible = false;
            return;
        }

        _layoutToggle.Icon = _gridLayout ? KsTguiIcons.ThList : KsTguiIcons.Th;
        _layoutToggle.ToolTip = Loc.GetString(_gridLayout ? "ks-tgui-vending-toggle-list" : "ks-tgui-vending-toggle-grid");

        var present = new HashSet<InventoryType>();
        foreach (var entry in _inventory)
            present.Add(entry.Type);

        if (!present.Contains(_selectedCategory))
            _selectedCategory = present.Contains(InventoryType.Regular) ? InventoryType.Regular : _inventory[0].Type;

        Control container = _gridLayout
            ? new WrapContainer { SeparationOverride = 4, CrossSeparationOverride = 4, HorizontalExpand = true }
            : new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, HorizontalExpand = true };
        _productsBody.AddChild(container);

        foreach (var entry in _inventory)
        {
            if (!_prototypeManager.TryIndex<EntityPrototype>(entry.ID, out var prototype))
                continue;

            var name = _contentLocalizationManager.GetLocalizedPrototypeName(prototype);

            // As tgui: a search of two letters or more looks through every category, otherwise one is shown.
            if (Searching)
            {
                if (!name.Contains(_searchBar.Text, StringComparison.CurrentCultureIgnoreCase))
                    continue;
            }
            else if (entry.Type != _selectedCategory)
            {
                continue;
            }

            var cell = new KsTguiVendingEntry(_gridLayout, entry.ID, name);
            cell.SetStock(entry.Amount, _enabled);
            var type = entry.Type;
            var id = entry.ID;
            cell.OnPressed += _ => OnVend?.Invoke(type, id);
            _entries[(type, id)] = cell;
            container.AddChild(cell);
        }

        RebuildCategories(present);
    }

    private void RebuildCategories(HashSet<InventoryType> present)
    {
        CategorySection.ClearBody();
        CategorySection.Visible = !Searching && present.Count > 1;
        if (!CategorySection.Visible)
            return;

        var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 2 };
        foreach (var type in new[] { InventoryType.Regular, InventoryType.Emagged, InventoryType.Contraband })
        {
            if (!present.Contains(type))
                continue;

            var button = new KsTguiButton
            {
                Text = Loc.GetString(type switch
                {
                    InventoryType.Emagged => "ks-tgui-vending-category-emagged",
                    InventoryType.Contraband => "ks-tgui-vending-category-contraband",
                    _ => "ks-tgui-vending-category-regular",
                }),
                Icon = type switch
                {
                    InventoryType.Emagged => KsTguiIcons.Star,
                    InventoryType.Contraband => KsTguiIcons.Skull,
                    _ => KsTguiIcons.Cart,
                },
                Color = type switch
                {
                    InventoryType.Emagged => KsTguiColor.Yellow,
                    InventoryType.Contraband => KsTguiColor.Red,
                    _ => KsTguiColor.Default,
                },
                Selected = type == _selectedCategory,
            };
            var captured = type;
            button.OnPressed += _ =>
            {
                _selectedCategory = captured;
                Rebuild();
            };
            row.AddChild(button);
        }

        CategorySection.AddChild(row);
    }
}
