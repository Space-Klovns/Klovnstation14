using System.Numerics;
using Content.Client.UserInterface.Controls;
using Content.Shared._KS14.McqDialogue;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._KS14.McqDialogue.UI;

[GenerateTypedNameReferences]
public sealed partial class McqDialogueWindow : FancyWindow
{
    private HashSet<string> _addedOptions = [];

    /// <summary>
    ///     The minimum size from the XAML, which <see cref="UpdateMinimumSize"/> only ever raises.
    /// </summary>
    private readonly Vector2 _baseMinSize;

    public McqDialogueWindow()
    {
        RobustXamlLoader.Load(this);
        _baseMinSize = MinSize;

        // Never cut short: the minimum size makes room for all of it instead. A clipped label also measures as zero
        //      wide, which would leave nothing to make room for.
        WindowTitle.ClipText = false;
    }

    protected override void Resized()
    {
        base.Resized();
        UpdateMinimumSize();
    }

    /// <summary>
    ///     Keeps the window from being resized small enough to cut off the title, the question or an option. None of
    ///         them wrap, so what they need at any width is what they need unconstrained.
    /// </summary>
    private void UpdateMinimumSize()
    {
        // Not laid out yet, so not styled yet either: the fonts aren't the ones it will be drawn with. Resized runs
        //      once it is.
        if (Size.X <= 0f)
            return;

        // The window's own measure includes its MinSize, so its children are measured instead, or it could never shrink
        //      back after a shorter title.
        var contentsSize = Vector2.Zero;
        foreach (var child in Children)
        {
            child.Measure(Vector2Helpers.Infinity);
            contentsSize = Vector2.Max(contentsSize, child.DesiredSize);
        }

        var minSize = Vector2.Max(_baseMinSize, contentsSize);
        if (minSize.EqualsApprox(MinSize, tolerance: 0.5))
            return;

        MinSize = minSize;

        // Dragging resizes through SetSize, which the new minimum overrides anyway; keep it in step so the next drag
        //      starts from the size actually shown.
        if (Size.X < minSize.X || Size.Y < minSize.Y)
            SetSize = Vector2.Max(Size, minSize);
    }

    /// <summary>
    ///     Replaces the default title and question with those given, where given.
    /// </summary>
    public void SetHeader(LocId? title, LocId? prompt)
    {
        if (title is { } titleId)
            Title = Loc.GetString(titleId);

        if (prompt is { } promptId)
            PromptLabel.Text = Loc.GetString(promptId);

        UpdateMinimumSize();
    }

    /// <summary>
    ///     Removes every option, for them to be added again with other handlers.
    /// </summary>
    public void ClearOptions()
    {
        OptionsContainer.RemoveAllChildren();
        _addedOptions.Clear();
        UpdateMinimumSize();
    }

    // Method to add a new option at runtime
    public void AddOption(McqDialogueData datum, Action handler)
    {
        if (!_addedOptions.Add(datum.Id))
            return;

        var button = new Button
        {
            Text = Loc.GetString(datum.LocId),
            //StyleClasses = { "OpenBoth" }
        };

        OptionsContainer.AddChild(button);
        button.OnPressed += (args) => { handler(); };
        UpdateMinimumSize();
    }
}
