using System.Numerics;
using Content.Client.Lobby.UI;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._KS14.Lobby.Kharkiv;

/// <summary>
///     The "Escape from Klovn" lobby layout: wordmark, season banner, centred menu, bottom tab bar, with its glare, bloom
///     and backdrop grade. It holds no lobby logic of its own: <c>LobbyGui</c> shows it instead of its tactical layout
///     and moves the controls both layouts share (ready, observe, manifest, leave, the countdown, vote popups, character
///     setup) into its slots. See Klovn/Docs/lobby.md.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class KsKharkivLobbySkin : LayoutContainer
{
    private static readonly ProtoId<ShaderPrototype> GradeShaderId = "KsLobbyGrade";

    private static readonly Color ReadyColor = Color.FromHex("#8FE05A");
    private static readonly Color NotReadyColor = Color.FromHex("#9A9A9A");
    private static readonly Color JoinColor = Color.FromHex("#F0A21E");

    [Dependency] private IPrototypeManager _prototypeManager = default!;

    private int _playerCount = -1;

    public KsKharkivLobbySkin()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        SetAnchorPreset(KsLightLeaks, LayoutPreset.Wide);
        SetAnchorPreset(KsFadeBottom, LayoutPreset.BottomWide);
        SetMarginTop(KsFadeBottom, -220);
        SetAnchorPreset(KsBloom, LayoutPreset.Wide);

        BackdropShader = _prototypeManager.Index(GradeShaderId).InstanceUnique();
        BannerPlayers.Text = "0";
    }

    /// <summary>
    ///     The backdrop grade (lobby_grade.swsl: darkening, curvature, slot mask, static) that LobbyGui puts on the lobby
    ///     art while this layout shows.
    /// </summary>
    public ShaderInstance BackdropShader { get; }

    /// <summary>Gives the grade the size of the quad it is drawn on, so its vignette and curve stay round.</summary>
    public void SetBackdropSize(Vector2 pixelSize)
    {
        BackdropShader.SetParameter("quadPixelSize", pixelSize);
    }

    public void SetBackdropStrength(float strength)
    {
        BackdropShader.SetParameter("strength", strength);
    }

    /// <summary>
    ///     Says under the title whether the player is ready, not ready, or can join the running round.
    /// </summary>
    public void SetReadyStatus(KsLobbyReadyStatus status)
    {
        var (key, color) = status switch
        {
            KsLobbyReadyStatus.Ready => ("ks-lobby-ready-ready", ReadyColor),
            KsLobbyReadyStatus.Join => ("ks-lobby-ready-join", JoinColor),
            _ => ("ks-lobby-ready-not-ready", NotReadyColor),
        };

        ReadyStatus.Text = Loc.GetString(key);
        ReadyStatus.FontColorOverride = color;
    }

    /// <summary>
    ///     Shows how many players are connected. Called every frame, so it only touches the label when the count changed.
    /// </summary>
    public void SetPlayerCount(int count)
    {
        if (count == _playerCount)
            return;

        _playerCount = count;
        BannerPlayers.Text = count.ToString();
    }

    /// <summary>Fills the build line, bottom left.</summary>
    public void SetVersionText(string text)
    {
        KsVersion.Text = text;
    }

    /// <summary>Shows the main menu or character setup.</summary>
    public void ShowSetup(bool setup)
    {
        MainMenu.Visible = !setup;
        SetupView.Visible = setup;
        // The editor is a form, not part of the menu's glowing chrome.
        KsBloom.BloomEnabled = !setup;
    }

    protected override void VisibilityChanged(bool newVisible)
    {
        base.VisibilityChanged(newVisible);

        // Hidden is the tactical layout showing, often for weeks: don't hold the bloom's screen-sized targets meanwhile.
        if (!newVisible)
            KsBloom.ReleaseTargets();
    }

    protected override void Dispose(bool disposing)
    {
        if (disposing)
            BackdropShader.Dispose();

        base.Dispose(disposing);
    }
}
