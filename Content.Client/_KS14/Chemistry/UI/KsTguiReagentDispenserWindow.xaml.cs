using Content.Client._KS14.UserInterface.Tgui;
using Content.Shared.Chemistry;
using Content.Shared.Chemistry.Reagent;
using Content.Shared.FixedPoint;
using Content.Shared.Storage;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._KS14.Chemistry.UI;

/// <summary>
///     The reagent dispenser, after /tg/'s ChemDispenser UI: the dispense amounts across the top, a grid of drop
///         buttons tinted with each reagent's colour, and the beaker's contents below. Here the reagents come from jugs,
///         so each button also says how much is left and has an eject button. Exposes the same API as the upstream
///         <c>ReagentDispenserWindow</c>, so <c>ReagentDispenserBoundUserInterface</c> can use either.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class KsTguiReagentDispenserWindow : KsTguiWindow
{
    private static readonly string[] Amounts = ["1", "5", "10", "15", "20", "30", "40", "60", "120"];

    [Dependency] private IPrototypeManager _prototypeManager = default!;

    private readonly List<KsTguiButton> _reagentButtons = new();
    private readonly List<ReagentInventoryItem> _inventory = new();

    public event Action<ItemStorageLocation>? OnDispenseReagentButtonPressed;
    public event Action<ItemStorageLocation>? OnEjectJugButtonPressed;
    public event Action? OnToggleValveButtonPressed; // Starlight-edit: Plumbing valve

    public KsTguiReagentDispenserWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        AmountGrid = new KsTguiChoiceButtons(AmountButtons, Amounts, KsTguiIconKind.Plus);
        ValveButton.OnPressed += _ => OnToggleValveButtonPressed?.Invoke();
    }

    /// <summary>
    ///     The dispense amounts. Raises <c>OnButtonPressed</c> with the amount as text, as the upstream button grid does.
    /// </summary>
    public KsTguiChoiceButtons AmountGrid { get; }

    public void UpdateState(BoundUserInterfaceState state)
    {
        var castState = (ReagentDispenserBoundUserInterfaceState)state;
        UpdateContainerInfo(castState);
        UpdateReagentsList(castState.Inventory);

        ClearButton.Disabled = castState.OutputContainer is null;
        EjectButton.Disabled = castState.OutputContainer is null;

        // Starlight-start
        ValveButton.Text = Loc.GetString(castState.ValveOpen ? "ks-tgui-chem-valve-open" : "ks-tgui-chem-valve-closed");
        ValveButton.Selected = castState.ValveOpen;
        // Starlight-end

        AmountGrid.Selected = ((int)castState.SelectedDispenseAmount).ToString();
    }

    /// <summary>
    ///     Fills the grid of dispense buttons, sorted by name. Buttons are reused while the jugs stay the same, so a
    ///         state update doesn't drop the one under the mouse.
    /// </summary>
    public void UpdateReagentsList(List<ReagentInventoryItem> inventory)
    {
        inventory.Sort((x, y) => string.Compare(x.ReagentLabel, y.ReagentLabel, StringComparison.CurrentCulture));

        if (_reagentButtons.Count != inventory.Count)
        {
            ReagentList.RemoveAllChildren();
            _reagentButtons.Clear();

            for (var i = 0; i < inventory.Count; i++)
            {
                _reagentButtons.Add(AddReagentCell(i));
            }
        }

        _inventory.Clear();
        _inventory.AddRange(inventory);
        NoJugsLabel.Visible = inventory.Count == 0;

        for (var i = 0; i < inventory.Count; i++)
        {
            var item = inventory[i];
            var dispense = _reagentButtons[i];
            dispense.Text = item.ReagentLabel;
            dispense.IconColor = item.ReagentColor;
            dispense.ToolTip = Loc.GetString("ks-tgui-chem-dispenser-jug-quantity", ("quantity", item.Quantity));
            dispense.Disabled = item.Quantity == FixedPoint2.Zero;
        }
    }

    /// <summary>
    ///     Adds the <paramref name="index"/>th grid cell, a dispense button and its jug's eject button, and returns the
    ///         dispense button. Both act on whichever jug is <paramref name="index"/>th in the latest state.
    /// </summary>
    private KsTguiButton AddReagentCell(int index)
    {
        var dispense = new KsTguiButton
        {
            Icon = KsTguiIconKind.Tint,
            HorizontalExpand = true,
            ClipText = true,
        };
        dispense.OnPressed += _ => OnDispenseReagentButtonPressed?.Invoke(_inventory[index].StorageLocation);

        var eject = new KsTguiButton
        {
            Icon = KsTguiIconKind.Eject,
            ButtonColor = KsTguiButtonColor.Transparent,
            ToolTip = Loc.GetString("ks-tgui-chem-dispenser-eject-jug"),
        };
        eject.OnPressed += _ => OnEjectJugButtonPressed?.Invoke(_inventory[index].StorageLocation);

        ReagentList.AddChild(new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            Children = { dispense, eject },
        });

        return dispense;
    }

    /// <summary>
    ///     Shows the beaker's fill and, as tgui's BeakerDisplay does, one "N units of Name" line per reagent.
    /// </summary>
    public void UpdateContainerInfo(ReagentDispenserBoundUserInterfaceState state)
    {
        ContainerInfo.RemoveAllChildren();

        if (state.OutputContainer is null)
        {
            ContainerInfoName.Text = Loc.GetString("ks-tgui-chem-no-beaker");
            ContainerInfoFill.Text = null;
            ContainerInfo.AddChild(new KsTguiLabel { Tone = KsTguiTone.Label, Text = Loc.GetString("ks-tgui-chem-nothing") });
            return;
        }

        ContainerInfoName.Text = state.OutputContainer.DisplayName;
        ContainerInfoFill.Text = Loc.GetString("ks-tgui-chem-volume",
            ("current", state.OutputContainer.CurrentVolume),
            ("max", state.OutputContainer.MaxVolume));

        var reagents = state.OutputContainer.Reagents;
        if (reagents == null || reagents.Count == 0)
        {
            ContainerInfo.AddChild(new KsTguiLabel { Tone = KsTguiTone.Label, Text = Loc.GetString("ks-tgui-chem-nothing") });
            return;
        }

        foreach (var (reagent, quantity) in reagents)
        {
            var name = _prototypeManager.TryIndex(reagent.Prototype, out ReagentPrototype? proto)
                ? proto.LocalizedName
                : Loc.GetString("reagent-dispenser-window-reagent-name-not-found-text");

            ContainerInfo.AddChild(new KsTguiLabel
            {
                Tone = KsTguiTone.Label,
                Text = Loc.GetString("ks-tgui-chem-units-of", ("volume", quantity), ("reagent", name)),
            });
        }
    }
}
