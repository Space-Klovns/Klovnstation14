/// <summary>
///     What a ChemMaster transfer button moves, carried by <see cref="KsTguiChemMasterWindow.OnReagentButtonPressed"/>
///         with the same members as the upstream <c>ReagentButton</c>.
/// </summary>
public sealed record KsTguiChemMasterTransfer(ReagentId Id, ChemMasterReagentAmount Amount, bool IsBuffer);

/// <summary>
///     The ChemMaster, after /tg/'s ChemMaster UI: the beaker and the buffer as rows of reagents with transfer buttons,
///         then packaging. It's one scrolling page, where the upstream window split input and output into tabs.
///         Exposes the same API as the upstream <c>ChemMasterWindow</c>, so <c>ChemMasterBoundUserInterface</c> can
///         use either.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class KsTguiChemMasterWindow : KsTguiWindow
{
    private const string PillsRsiPath = "/Textures/Objects/Specific/Chemistry/pills.rsi";
    private const int PillTypes = 20;

    private static readonly (string Text, ChemMasterReagentAmount Amount)[] TransferAmounts =
    [
        ("1", ChemMasterReagentAmount.U1),
        ("5", ChemMasterReagentAmount.U5),
        ("10", ChemMasterReagentAmount.U10),
        ("15", ChemMasterReagentAmount.U15),
        ("20", ChemMasterReagentAmount.U20),
        ("30", ChemMasterReagentAmount.U30),
        ("40", ChemMasterReagentAmount.U40),
        ("60", ChemMasterReagentAmount.U60),
        ("120", ChemMasterReagentAmount.U120),
    ];

    [Dependency] private IPrototypeManager _prototypeManager = default!;
    [Dependency] private IEntityManager _entityManager = default!;

    public event Action<BaseButton.ButtonEventArgs, KsTguiChemMasterTransfer>? OnReagentButtonPressed;
    public event Action? OnToggleValveButtonPressed; // Starlight-edit: Plumbing valve

    public readonly KsTguiButton[] PillTypeButtons = new KsTguiButton[PillTypes];

    public KsTguiChemMasterWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        var spriteSystem = _entityManager.System<SpriteSystem>();
        var pillsPath = new ResPath(PillsRsiPath);
        for (var i = 0; i < PillTypes; i++)
        {
            var button = new KsTguiButton
            {
                ButtonColor = KsTguiButtonColor.Transparent,
                SetSize = new Vector2(30f, 30f),
            };
            button.AddChild(new TextureRect
            {
                Texture = spriteSystem.Frame0(new SpriteSpecifier.Rsi(pillsPath, "pill" + (i + 1))),
                TextureScale = new Vector2(1.5f, 1.5f),
                Stretch = TextureRect.StretchMode.KeepCentered,
                MouseFilter = MouseFilterMode.Ignore,
            });
            PillTypeButtons[i] = button;
            Grid.AddChild(button);
        }

        LabelLineEdit.IsValid = s => s.Length <= SharedChemMaster.LabelMaxLength;
        ValveButton.OnPressed += _ => OnToggleValveButtonPressed?.Invoke(); // Starlight-edit: Plumbing valve
    }

    public string LabelLine
    {
        get => LabelLineEdit.Text;
        set => LabelLineEdit.Text = value;
    }

    /// <summary>
    ///     Update the UI state when new state data is received from the server.
    /// </summary>
    public void UpdateState(BoundUserInterfaceState state)
    {
        var castState = (ChemMasterBoundUserInterfaceState)state;

        if (castState.UpdateLabel)
            LabelLine = GenerateLabel(castState);

        UpdatePanelInfo(castState);

        switch (castState.DrawSource)
        {
            case ChemMasterDrawSource.Internal:
                SetBufferText(castState.BufferCurrentVolume);
                break;
            case ChemMasterDrawSource.External:
                SetBufferText(castState.InputContainerInfo?.CurrentVolume);
                break;
            default:
                throw new($"Chemmaster {castState.OutputContainerInfo} draw source is not set");
        }

        InputEjectButton.Disabled = castState.InputContainerInfo is null;
        OutputEjectButton.Disabled = castState.OutputContainerInfo is null;
        CreateBottleButton.Disabled = castState.OutputContainerInfo?.Reagents == null;

        // Starlight-start: Plumbing valve
        ValveButton.Text = Loc.GetString(castState.ValveOpen ? "ks-tgui-chem-valve-open" : "ks-tgui-chem-valve-closed");
        ValveButton.Selected = castState.ValveOpen;
        // Starlight-end

        for (var i = 0; i < PillTypeButtons.Length; i++)
        {
            // An image button shows selected as a green block; tgui's transparent buttons only tint text green.
            PillTypeButtons[i].ButtonColor = i == castState.SelectedPillType ? KsTguiButtonColor.Green : KsTguiButtonColor.Transparent;
        }

        UpdateDosageFields(castState);
    }

    /// <summary>
    ///     The upstream window's defaults and limits for the pill and bottle fields: fill what's there, never past the
    ///         output container's free space.
    /// </summary>
    private void UpdateDosageFields(ChemMasterBoundUserInterfaceState castState)
    {
        var output = castState.OutputContainerInfo;
        var remainingCapacity = output is null ? 0 : (output.MaxVolume - output.CurrentVolume).Int();
        var holdsReagents = output?.Reagents != null;
        var pillNumberMax = holdsReagents ? 0 : remainingCapacity;
        var bottleAmountMax = holdsReagents ? remainingCapacity : 0;
        var outputVolume = castState.DrawSource switch
        {
            ChemMasterDrawSource.Internal => castState.BufferCurrentVolume?.Int() ?? 0,
            ChemMasterDrawSource.External => castState.InputContainerInfo?.CurrentVolume.Int() ?? 0,
            _ => 0,
        };

        PillDosage.MaxValue = castState.PillDosageLimit;
        PillNumber.MaxValue = pillNumberMax;
        BottleDosage.MaxValue = bottleAmountMax;

        PillDosage.Value = Math.Min(outputVolume, (int)castState.PillDosageLimit);
        PillNumber.Value = PillDosage.Value > 0 ? Math.Min(outputVolume / (int)PillDosage.Value, pillNumberMax) : 0;
        BottleDosage.Value = Math.Min(bottleAmountMax, outputVolume);
    }

    /// <summary>
    ///     Names the product after the least plentiful reagent in whichever source it's drawn from, as upstream.
    /// </summary>
    private string GenerateLabel(ChemMasterBoundUserInterfaceState state)
    {
        if (state.BufferCurrentVolume == 0 && state.DrawSource == ChemMasterDrawSource.Internal ||
            state.InputContainerInfo?.CurrentVolume == 0 && state.DrawSource == ChemMasterDrawSource.External ||
            state.InputContainerInfo?.Reagents == null)
            return "";

        var reagent = (state.DrawSource switch
            {
                ChemMasterDrawSource.Internal => state.BufferReagents,
                ChemMasterDrawSource.External => state.InputContainerInfo.Reagents ?? [],
                _ => throw new($"Chemmaster {state.OutputContainerInfo} draw source is not set"),
            }).MinBy(r => r.Quantity)
            .Reagent;
        _prototypeManager.TryIndex(reagent.Prototype, out ReagentPrototype? proto);
        return proto?.LocalizedName ?? "";
    }

    private void UpdatePanelInfo(ChemMasterBoundUserInterfaceState state)
    {
        // Each mode button shows only while it's the current mode, and pressing it sets the other one.
        BufferTransferButton.Visible = state.Mode == ChemMasterMode.Discard;
        BufferDiscardButton.Visible = state.Mode == ChemMasterMode.Transfer;

        BufferSortButton.Text = state.SortingType switch
        {
            ChemMasterSortingType.Alphabetical => Loc.GetString("chem-master-window-sort-type-alphabetical"),
            ChemMasterSortingType.Quantity => Loc.GetString("chem-master-window-sort-type-quantity"),
            ChemMasterSortingType.Latest => Loc.GetString("chem-master-window-sort-type-latest"),
            _ => Loc.GetString("chem-master-window-sort-type-none"),
        };

        OutputBufferDraw.Selected = state.DrawSource == ChemMasterDrawSource.Internal;
        OutputBeakerDraw.Selected = state.DrawSource == ChemMasterDrawSource.External;

        BuildContainerUI(InputContainerInfo, InputVolumeLabel, state.InputContainerInfo, addReagentButtons: true);
        BuildOutputContainerUI(state.OutputContainerInfo);

        BufferInfo.RemoveAllChildren();
        BufferVolumeLabel.Text = Loc.GetString("ks-tgui-chem-master-buffer-volume", ("volume", state.BufferCurrentVolume ?? FixedPoint2.Zero));

        if (!state.BufferReagents.Any())
        {
            BufferInfo.AddChild(new KsTguiLabel { Tone = KsTguiTone.Label, Text = Loc.GetString("ks-tgui-chem-master-buffer-empty") });
            return;
        }

        var reagentList = new List<(ReagentId ReagentId, string Name, Color Color, FixedPoint2 Quantity)>();
        foreach (var (reagent, quantity) in state.BufferReagents)
        {
            _prototypeManager.TryIndex(reagent.Prototype, out ReagentPrototype? proto);
            var name = proto?.LocalizedName ?? Loc.GetString("chem-master-window-unknown-reagent-text");
            reagentList.Add((reagent, name, proto?.SubstanceColor ?? default, quantity));
        }

        reagentList = state.SortingType switch
        {
            ChemMasterSortingType.Alphabetical => reagentList.OrderBy(x => x.Name).ToList(),
            ChemMasterSortingType.Quantity => reagentList.OrderByDescending(x => x.Quantity).ToList(),
            ChemMasterSortingType.Latest => Enumerable.Reverse(reagentList).ToList(),
            _ => reagentList,
        };

        foreach (var reagent in reagentList)
        {
            BufferInfo.AddChild(BuildReagentRow(reagent.Color, reagent.Name, reagent.ReagentId, reagent.Quantity, isBuffer: true, addReagentButtons: true));
        }
    }

    private void BuildContainerUI(Control control, Label volumeLabel, ContainerInfo? info, bool addReagentButtons)
    {
        control.RemoveAllChildren();

        if (info is null)
        {
            volumeLabel.Text = null;
            control.AddChild(new KsTguiLabel { Tone = KsTguiTone.Label, Text = Loc.GetString("ks-tgui-chem-no-beaker") });
            return;
        }

        volumeLabel.Text = Loc.GetString("ks-tgui-chem-volume-spaced", ("current", info.CurrentVolume), ("max", info.MaxVolume));

        if (info.CurrentVolume == FixedPoint2.Zero && (info.Entities == null || info.Entities.Count == 0))
        {
            control.AddChild(new KsTguiLabel { Tone = KsTguiTone.Label, Text = Loc.GetString("ks-tgui-chem-beaker-empty") });
            return;
        }

        if (info.Entities != null)
        {
            foreach (var (id, quantity) in info.Entities)
            {
                control.AddChild(BuildReagentRow(default, id, default, quantity, isBuffer: false, addReagentButtons: false));
            }
        }

        if (info.Reagents == null)
            return;

        foreach (var reagent in info.Reagents)
        {
            _prototypeManager.TryIndex(reagent.Reagent.Prototype, out ReagentPrototype? proto);
            var name = proto?.LocalizedName ?? Loc.GetString("chem-master-window-unknown-reagent-text");
            control.AddChild(BuildReagentRow(proto?.SubstanceColor ?? default, name, reagent.Reagent, reagent.Quantity, isBuffer: false, addReagentButtons));
        }
    }

    private void BuildOutputContainerUI(ContainerInfo? info)
    {
        OutputContainerInfo.RemoveAllChildren();

        if (info is null)
        {
            OutputContainerInfo.AddChild(new KsTguiLabel { Tone = KsTguiTone.Label, Text = Loc.GetString("ks-tgui-chem-master-no-container") });
            return;
        }

        OutputContainerInfo.AddChild(new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            SeparationOverride = 6,
            Children =
            {
                new KsTguiLabel { Text = info.DisplayName },
                new KsTguiLabel
                {
                    Tone = KsTguiTone.Label,
                    Text = Loc.GetString("ks-tgui-chem-volume", ("current", info.CurrentVolume), ("max", info.MaxVolume)),
                },
            },
        });

        if (info.Entities != null)
        {
            foreach (var (id, quantity) in info.Entities)
            {
                OutputContainerInfo.AddChild(BuildReagentRow(default, id, default, quantity, isBuffer: false, addReagentButtons: false));
            }
        }

        if (info.Reagents == null)
            return;

        foreach (var reagent in info.Reagents)
        {
            _prototypeManager.TryIndex(reagent.Reagent.Prototype, out ReagentPrototype? proto);
            var name = proto?.LocalizedName ?? Loc.GetString("chem-master-window-unknown-reagent-text");
            OutputContainerInfo.AddChild(BuildReagentRow(proto?.SubstanceColor ?? default, name, reagent.Reagent, reagent.Quantity, isBuffer: false, addReagentButtons: false));
        }
    }

    /// <summary>
    ///     A reagent's colour swatch, "Name 12u" in the label colour, and its transfer buttons.
    /// </summary>
    private Control BuildReagentRow(Color reagentColor, string name, ReagentId reagent, FixedPoint2 quantity, bool isBuffer, bool addReagentButtons)
    {
        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            SeparationOverride = 2,
        };

        row.AddChild(new PanelContainer
        {
            SetSize = new Vector2(8f, 8f),
            Margin = new Thickness(0f, 0f, 4f, 0f),
            VerticalAlignment = VAlignment.Center,
            PanelOverride = new StyleBoxFlat { BackgroundColor = reagentColor == default ? Color.Black.WithAlpha(0f) : reagentColor },
        });

        row.AddChild(new KsTguiLabel
        {
            Tone = KsTguiTone.Label,
            Text = Loc.GetString("ks-tgui-chem-reagent-volume", ("reagent", name), ("volume", quantity)),
            ClipText = true,
            HorizontalExpand = true,
            MinHeight = KsTguiTheme.ButtonHeight,
        });

        if (!addReagentButtons)
            return row;

        foreach (var (text, amount) in TransferAmounts)
        {
            row.AddChild(MakeTransferButton(text, new KsTguiChemMasterTransfer(reagent, amount, isBuffer)));
        }

        row.AddChild(MakeTransferButton(Loc.GetString("ks-tgui-chem-master-all"),
            new KsTguiChemMasterTransfer(reagent, ChemMasterReagentAmount.All, isBuffer)));

        return row;
    }

    private KsTguiButton MakeTransferButton(string text, KsTguiChemMasterTransfer transfer)
    {
        var button = new KsTguiButton { Text = text };
        button.OnPressed += args => OnReagentButtonPressed?.Invoke(args, transfer);
        return button;
    }

    private void SetBufferText(FixedPoint2? volume)
    {
        BufferCurrentVolume.Text = Loc.GetString("ks-tgui-chem-master-buffer-volume", ("volume", volume ?? FixedPoint2.Zero));
    }
}
