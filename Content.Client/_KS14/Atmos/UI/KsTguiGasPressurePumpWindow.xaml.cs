using Content.Client._KS14.UserInterface.Tgui;
using Content.Shared.Atmos;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._KS14.Atmos.UI;

/// <summary>
///     The pressure pump, after /tg/'s AtmosPump UI. Exposes the same API as the upstream
///         <c>GasPressurePumpWindow</c>, so <c>GasPressurePumpBoundUserInterface</c> can use either.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class KsTguiGasPressurePumpWindow : KsTguiWindow
{
    public event Action<bool>? ToggleStatusButtonPressed;
    public event Action<float>? PumpOutputPressureChanged;

    private bool _enabled;

    public KsTguiGasPressurePumpWindow()
    {
        RobustXamlLoader.Load(this);

        PressureInput.MaxValue = Atmospherics.MaxOutputPressure;
        PressureInput.OnValueChanged += value => PumpOutputPressureChanged?.Invoke(value);
        PowerButton.OnPressed += _ => ToggleStatusButtonPressed?.Invoke(!_enabled);
        MaxButton.OnPressed += _ => PressureInput.SubmitValue(PressureInput.MaxValue);

        SetPumpStatus(false);
    }

    public float MaxPressure
    {
        get => PressureInput.MaxValue;
        set
        {
            PressureInput.MaxValue = value;
            UpdateMaxButton();
        }
    }

    public void SetOutputPressure(float pressure)
    {
        PressureInput.Value = pressure;
        UpdateMaxButton();
    }

    public void SetPumpStatus(bool enabled)
    {
        _enabled = enabled;
        KsTguiPowerButton.Apply(PowerButton, enabled);
    }

    private void UpdateMaxButton()
    {
        MaxButton.Disabled = MathHelper.CloseTo(PressureInput.Value, PressureInput.MaxValue);
    }
}
