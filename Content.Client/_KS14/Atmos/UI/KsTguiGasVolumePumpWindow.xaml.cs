using System.Globalization;
using Content.Client._KS14.UserInterface.Tgui;
using Content.Shared.Atmos;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._KS14.Atmos.UI;

/// <summary>
///     The volume pump, after /tg/'s AtmosPump UI in its transfer-rate form. Exposes the same API as the upstream
///         <c>GasVolumePumpWindow</c>, so <c>GasVolumePumpBoundUserInterface</c> can use either.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class KsTguiGasVolumePumpWindow : KsTguiWindow
{
    public event Action<bool>? ToggleStatusButtonPressed;

    /// <summary>
    ///     The new rate as text, as the upstream window sends it; the interface parses and clamps it.
    /// </summary>
    public event Action<string>? PumpTransferRateChanged;

    private bool _enabled;

    public KsTguiGasVolumePumpWindow()
    {
        RobustXamlLoader.Load(this);

        RateInput.MaxValue = Atmospherics.MaxTransferRate;
        RateInput.OnValueChanged += value => PumpTransferRateChanged?.Invoke(value.ToString(CultureInfo.CurrentCulture));
        PowerButton.OnPressed += _ => ToggleStatusButtonPressed?.Invoke(!_enabled);
        MaxButton.OnPressed += _ => RateInput.SubmitValue(RateInput.MaxValue);

        SetPumpStatus(false);
    }

    public void SetTransferRate(float rate)
    {
        RateInput.Value = rate;
        MaxButton.Disabled = MathHelper.CloseTo(RateInput.Value, RateInput.MaxValue);
    }

    public void SetPumpStatus(bool enabled)
    {
        _enabled = enabled;
        KsTguiPowerButton.Apply(PowerButton, enabled);
    }
}
