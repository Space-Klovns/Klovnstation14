using System.Globalization;
using Content.Client._KS14.UserInterface.Tgui;
using Content.Shared.Atmos;
using Content.Shared.Atmos.Prototypes;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._KS14.Atmos.UI;

/// <summary>
///     The gas filter, after /tg/'s AtmosFilter UI: one check button per gas, any number of them on at once.
///         Exposes the same API as the upstream <c>GasFilterWindow</c>, so <c>GasFilterBoundUserInterface</c> can use either.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class KsTguiGasFilterWindow : KsTguiWindow
{
    private readonly Dictionary<Gas, KsTguiButton> _gasButtons = new();
    private readonly HashSet<Gas> _selectedGases = new();

    public event Action<bool>? ToggleStatusButtonPressed;

    /// <summary>
    ///     The new rate as text, as the upstream window sends it; the interface parses it.
    /// </summary>
    public event Action<string>? FilterTransferRateChanged;

    public event Action<HashSet<Gas>>? FilterGasesChanged;

    public KsTguiGasFilterWindow()
    {
        RobustXamlLoader.Load(this);

        RateInput.MaxValue = Atmospherics.MaxTransferRate;
        RateInput.OnValueChanged += value => FilterTransferRateChanged?.Invoke(value.ToString(CultureInfo.CurrentCulture));
        MaxButton.OnPressed += _ => RateInput.SubmitValue(RateInput.MaxValue);
        PowerButton.OnPressed += _ => ToggleStatusButtonPressed?.Invoke(!FilterStatus);
        SelectAllButton.OnPressed += _ => SetAllGases(true);
        DeselectAllButton.OnPressed += _ => SetAllGases(false);

        SetFilterStatus(false);
    }

    public bool FilterStatus { get; private set; }

    public void SetFilterStatus(bool enabled)
    {
        FilterStatus = enabled;
        KsTguiPowerButton.Apply(PowerButton, enabled);
    }

    public void SetTransferRate(float rate)
    {
        RateInput.Value = rate;
        MaxButton.Disabled = MathHelper.CloseTo(RateInput.Value, RateInput.MaxValue);
    }

    public void SetFilteredGases(HashSet<Gas> gases)
    {
        _selectedGases.Clear();
        _selectedGases.UnionWith(gases);

        foreach (var (gas, button) in _gasButtons)
        {
            ShowGasSelected(button, gases.Contains(gas));
        }
    }

    public void PopulateGasList(IEnumerable<GasPrototype> gases)
    {
        foreach (var gas in gases)
        {
            if (!Enum.TryParse<Gas>(gas.ID, out var gasEnum) || _gasButtons.ContainsKey(gasEnum))
                continue;

            var button = new KsTguiButton
            {
                Text = Loc.GetString(gas.Name),
                HorizontalExpand = true,
                ClipText = true,
            };
            ShowGasSelected(button, _selectedGases.Contains(gasEnum));
            button.OnPressed += _ => ToggleGas(gasEnum);

            _gasButtons.Add(gasEnum, button);
            GasContainer.AddChild(button);
        }
    }

    private void ToggleGas(Gas gas)
    {
        if (!_selectedGases.Remove(gas))
            _selectedGases.Add(gas);

        ShowGasSelected(_gasButtons[gas], _selectedGases.Contains(gas));
        FilterGasesChanged?.Invoke(new HashSet<Gas>(_selectedGases));
    }

    private void SetAllGases(bool selected)
    {
        _selectedGases.Clear();
        if (selected)
            _selectedGases.UnionWith(_gasButtons.Keys);

        foreach (var button in _gasButtons.Values)
        {
            ShowGasSelected(button, selected);
        }

        FilterGasesChanged?.Invoke(new HashSet<Gas>(_selectedGases));
    }

    private static void ShowGasSelected(KsTguiButton button, bool selected)
    {
        button.Icon = selected ? KsTguiIconKind.CheckSquare : KsTguiIconKind.Square;
        button.Selected = selected;
    }
}
