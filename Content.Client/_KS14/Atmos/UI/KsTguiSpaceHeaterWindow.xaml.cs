using Content.Client._KS14.UserInterface.Tgui;
using Content.Shared.Atmos;
using Content.Shared.Atmos.Piping.Portable.Components;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._KS14.Atmos.UI;

/// <summary>
///     The space heater, after /tg/'s SpaceHeater UI. Space heaters here run off the grid, so the cell bar becomes the
///         power level, and the target is set in steps of <see cref="TemperatureStep"/>.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class KsTguiSpaceHeaterWindow : KsTguiWindow
{
    /// <summary>
    ///     Atmos only equalizes past a minimum temperature difference, so the target moves in fixed steps, as upstream.
    /// </summary>
    public const float TemperatureStep = 5f;

    private readonly Dictionary<SpaceHeaterMode, KsTguiButton> _modeButtons = new();
    private readonly Dictionary<SpaceHeaterPowerLevel, KsTguiButton> _powerLevelButtons = new();

    private float _targetTemperature;

    public event Action? OnToggle;

    /// <summary>
    ///     How far, in kelvin, to move the target. The server takes a change, not a new target.
    /// </summary>
    public event Action<float>? OnTemperatureChange;

    public event Action<SpaceHeaterMode>? OnModeChange;
    public event Action<SpaceHeaterPowerLevel>? OnPowerLevelChange;

    public KsTguiSpaceHeaterWindow()
    {
        RobustXamlLoader.Load(this);

        PowerButton.OnPressed += _ => OnToggle?.Invoke();
        TargetInput.Step = TemperatureStep;
        TargetInput.OnValueChanged += celsius => OnTemperatureChange?.Invoke(celsius + Atmospherics.T0C - _targetTemperature);

        foreach (var mode in Enum.GetValues<SpaceHeaterMode>())
        {
            var button = new KsTguiButton
            {
                Text = Loc.GetString($"comp-space-heater-mode-{mode}"),
                Icon = mode switch
                {
                    SpaceHeaterMode.Heat => KsTguiIconKind.Fire,
                    SpaceHeaterMode.Cool => KsTguiIconKind.Snowflake,
                    _ => KsTguiIconKind.Thermometer,
                },
            };
            button.OnPressed += _ => OnModeChange?.Invoke(mode);
            _modeButtons.Add(mode, button);
            ModeRow.AddChild(button);
        }

        foreach (var level in Enum.GetValues<SpaceHeaterPowerLevel>())
        {
            var button = new KsTguiButton { Text = Loc.GetString($"comp-space-heater-ui-{level}-power-consumption") };
            button.OnPressed += _ => OnPowerLevelChange?.Invoke(level);
            _powerLevelButtons.Add(level, button);
            PowerLevelRow.AddChild(button);
        }

        KsTguiPowerButton.Apply(PowerButton, false);
    }

    public void UpdateState(SpaceHeaterBoundUserInterfaceState state)
    {
        KsTguiPowerButton.Apply(PowerButton, state.Enabled);

        _targetTemperature = state.TargetTemperature;
        TargetInput.MinValue = state.MinTemperature - Atmospherics.T0C;
        TargetInput.MaxValue = state.MaxTemperature - Atmospherics.T0C;
        TargetInput.Value = state.TargetTemperature - Atmospherics.T0C;

        foreach (var (mode, button) in _modeButtons)
        {
            button.Selected = mode == state.Mode;
        }

        foreach (var (level, button) in _powerLevelButtons)
        {
            button.Selected = level == state.PowerLevel;
        }
    }
}
