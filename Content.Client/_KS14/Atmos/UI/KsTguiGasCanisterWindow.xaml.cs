using Content.Client._KS14.UserInterface.Tgui;
using Content.Shared.Atmos;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._KS14.Atmos.UI;

/// <summary>
///     The gas canister, after /tg/'s Canister UI: a pressure gauge, the release regulator knob, the valve and the
///         port, then the battery shield, then the holding tank. Exposes the same API as the upstream
///         <c>GasCanisterWindow</c> and its shielding partial, so <c>GasCanisterBoundUserInterface</c> can use either.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class KsTguiGasCanisterWindow : KsTguiWindow
{
    public event Action? TankEjectButtonPressed;
    public event Action<float>? ReleasePressureSet;
    public event Action? ReleaseValveCloseButtonPressed;
    public event Action? ReleaseValveOpenButtonPressed;
    public event Action? ShieldToggleButtonPressed;

    private bool _valveOpen;
    private bool _hasTank;

    public KsTguiGasCanisterWindow()
    {
        RobustXamlLoader.Load(this);

        ReleaseKnob.OnValueChanged += value => ReleasePressureSet?.Invoke(value);
        ReleaseKnob.OnValueShown += _ => UpdateReleaseLabel();
        ReleaseMaxButton.OnPressed += _ => ReleaseKnob.SubmitValue(ReleaseKnob.MaxValue);
        ReleaseResetButton.OnPressed += _ => ReleaseKnob.SubmitValue(Atmospherics.OneAtmosphere);

        ValveButton.OnPressed += _ =>
        {
            if (_valveOpen)
                ReleaseValveCloseButtonPressed?.Invoke();
            else
                ReleaseValveOpenButtonPressed?.Invoke();
        };

        TankEjectButton.OnPressed += _ => TankEjectButtonPressed?.Invoke();
        ShieldToggleButton.OnPressed += _ => ShieldToggleButtonPressed?.Invoke();

        SetPressureLimits(CanisterGauge, 15f * Atmospherics.OneAtmosphere, 20f * Atmospherics.OneAtmosphere);
        SetPressureLimits(TankGauge, 15f * Atmospherics.OneAtmosphere, 20f * Atmospherics.OneAtmosphere);
        SetReleaseValve(false);
        SetPortStatus(false);
        SetTankLabel(null);
    }

    public void SetCanisterLabel(string label)
    {
        Title = label;
    }

    public void SetCanisterPressure(float pressure)
    {
        CanisterGauge.Value = pressure;
        CanisterGauge.Text = KsTguiFormat.Pressure(pressure);
    }

    /// <summary>
    ///     Where the safety valve opens and where the canister bursts, for the gauge's bands.
    /// </summary>
    public void SetCanisterPressureLimits(float safetyPressure, float overpressure)
    {
        SetPressureLimits(CanisterGauge, safetyPressure, overpressure);
    }

    public void SetPortStatus(bool status)
    {
        PortIcon.Kind = status ? KsTguiIconKind.Plug : KsTguiIconKind.Times;
        PortIcon.Color = KsTguiTheme.ToneText(status ? KsTguiTone.Good : KsTguiTone.Bad);
        PortIcon.ToolTip = Loc.GetString(status
            ? "ks-tgui-atmos-canister-port-connected"
            : "ks-tgui-atmos-canister-port-disconnected");
    }

    public void SetTankLabel(string? label)
    {
        _hasTank = label != null;
        TankInfo.Visible = _hasTank;
        NoTankLabel.Visible = !_hasTank;
        TankEjectButton.Visible = _hasTank;
        TankLabelLabel.Text = label;
        UpdateValveColors();
    }

    public void SetTankPressure(float pressure)
    {
        TankGauge.Value = pressure;
        TankGauge.Text = KsTguiFormat.Pressure(pressure);
    }

    /// <summary>
    ///     The holding tank's own safety and burst pressures, for its gauge's bands.
    /// </summary>
    public void SetTankPressureLimits(float safetyPressure, float overpressure)
    {
        SetPressureLimits(TankGauge, safetyPressure, overpressure);
    }

    public void SetReleasePressureRange(float min, float max)
    {
        ReleaseKnob.MinValue = min;
        ReleaseKnob.MaxValue = max;
        UpdateReleaseLabel();
    }

    public void SetReleasePressure(float pressure)
    {
        ReleaseKnob.Value = pressure;
        UpdateReleaseLabel();
    }

    public void SetReleaseValve(bool valve)
    {
        _valveOpen = valve;
        ValveButton.Text = Loc.GetString(valve ? "ks-tgui-atmos-canister-valve-open" : "ks-tgui-atmos-canister-valve-closed");
        UpdateValveColors();
    }

    public void SetShieldSettingsVisible(bool visible)
    {
        ShieldSettingsContainer.Visible = visible;
        ShieldToggleButton.Visible = visible;
    }

    public void UpdateShieldState(bool enabled, float dischargeRate, float lastCharge, float maxCharge)
    {
        ShieldToggleButton.Icon = enabled ? KsTguiIconKind.PowerOff : KsTguiIconKind.Times;
        ShieldToggleButton.Text = Loc.GetString(enabled ? "ks-tgui-atmos-canister-shielding-on" : "ks-tgui-atmos-canister-shielding-off");
        ShieldToggleButton.Selected = enabled;
        ShieldToggleButton.Disabled = lastCharge < dischargeRate;

        var charge = maxCharge > 0f ? lastCharge / maxCharge : 0f;
        ShieldChargeBar.Value = charge;
        ShieldChargeBar.Tone = KsTguiTheme.ToneAbove(charge, goodFrom: 0.6f, averageFrom: 0.3f);
        ShieldWattage.Text = Loc.GetString("ks-tgui-atmos-canister-shield-wattage", ("wattage", dischargeRate));
    }

    private void UpdateValveColors()
    {
        // tgui warns harder when the gas goes straight into the room rather than into a tank.
        ValveButton.ButtonColor = !_valveOpen
            ? KsTguiButtonColor.Default
            : _hasTank ? KsTguiButtonColor.Caution : KsTguiButtonColor.Danger;
        ReleaseKnob.RingColor = _valveOpen ? KsTguiTheme.Yellow : KsTguiTheme.BorderPrimary;
        TankEjectButton.ButtonColor = _valveOpen ? KsTguiButtonColor.Danger : KsTguiButtonColor.Default;
    }

    private void UpdateReleaseLabel()
    {
        ReleaseLabel.Text = ReleaseKnob.FormatValue();
        ReleaseMaxButton.Disabled = MathHelper.CloseTo(ReleaseKnob.Value, ReleaseKnob.MaxValue);
        ReleaseResetButton.Disabled = MathHelper.CloseTo(ReleaseKnob.Value, Atmospherics.OneAtmosphere);
    }

    /// <summary>
    ///     Green below the safety valve's pressure, orange up to bursting, red past it, as tgui bands a tank's gauge.
    /// </summary>
    private static void SetPressureLimits(KsTguiRoundGauge gauge, float safetyPressure, float overpressure)
    {
        gauge.MinValue = 0f;
        gauge.MaxValue = overpressure * 1.15f;
        gauge.AverageFrom = safetyPressure;
        gauge.BadFrom = overpressure;
        gauge.AlertAfter = safetyPressure;
    }
}
