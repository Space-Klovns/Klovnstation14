using Content.Client._KS14.UserInterface.Tgui;
using Content.Shared.Atmos;
using Content.Shared.Atmos.Components;
using Content.Shared.Atmos.EntitySystems;
using Content.Shared.Timing;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client._KS14.Atmos.UI;

/// <summary>
///     The gas tank, after /tg/'s Tank UI: a pressure gauge and the release regulator, plus the internals switch that
///         /tg/ keeps on an action button instead. Exposes the same API as the upstream <c>GasTankWindow</c>, so
///         <c>GasTankBoundUserInterface</c> can use either.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class KsTguiGasTankWindow : KsTguiWindow
{
    [Dependency] private IEntityManager _entityManager = default!;

    public EntityUid Entity;

    public event Action<float>? OnOutputPressure;
    public event Action? OnToggleInternals;

    public KsTguiGasTankWindow()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);

        ReleaseInput.MinValue = Atmospherics.OneAtmosphere / 10f;
        ReleaseInput.MaxValue = 3f * Atmospherics.OneAtmosphere;
        ReleaseInput.OnValueChanged += value => OnOutputPressure?.Invoke(value);
        ReleaseInput.OnValueShown += _ => UpdateRegulatorButtons();
        MinimumButton.OnPressed += _ => ReleaseInput.SubmitValue(ReleaseInput.MinValue);
        MaximumButton.OnPressed += _ => ReleaseInput.SubmitValue(ReleaseInput.MaxValue);
        ResetButton.OnPressed += _ => ReleaseInput.SubmitValue(Atmospherics.OneAtmosphere);
        InternalsButton.OnPressed += _ => OnToggleInternals?.Invoke();

        PressureGauge.MaxValue = 20f * Atmospherics.OneAtmosphere * 1.15f;
        ShowInternals(false);
        UpdateRegulatorButtons();
    }

    public void SetTitle(string name)
    {
        Title = name;
    }

    public void UpdateState(GasTankBoundUserInterfaceState state)
    {
        PressureGauge.Value = state.TankPressure;
        PressureGauge.Text = KsTguiFormat.Pressure(state.TankPressure);
    }

    public void Update(bool canConnectInternals, bool internalsConnected, float outputPressure)
    {
        ShowInternals(internalsConnected);
        InternalsButton.Disabled = !canConnectInternals;
        ReleaseInput.Value = outputPressure;
        UpdateRegulatorButtons();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        // Easier than managing state on any ent changes, as the upstream window does.
        if (!_entityManager.TryGetComponent(Entity, out GasTankComponent? tank))
            return;

        var disabled = !_entityManager.System<SharedGasTankSystem>().CanConnectToInternals((Entity, tank)) ||
                       _entityManager.System<UseDelaySystem>().IsDelayed(Entity, id: SharedGasTankSystem.GasTankDelay);
        if (InternalsButton.Disabled != disabled)
            InternalsButton.Disabled = disabled;

        if (!MathHelper.CloseTo(ReleaseInput.MinValue, tank.MinReleasePressure) ||
            !MathHelper.CloseTo(ReleaseInput.MaxValue, tank.MaxReleasePressure))
        {
            ReleaseInput.MinValue = tank.MinReleasePressure;
            ReleaseInput.MaxValue = tank.MaxReleasePressure;
            UpdateRegulatorButtons();
        }

        // Green until the safety valve would vent, orange until it bursts.
        PressureGauge.MaxValue = tank.Overpressure * 1.15f;
        PressureGauge.AverageFrom = tank.SafetyPressure;
        PressureGauge.BadFrom = tank.Overpressure;
        PressureGauge.AlertAfter = tank.SafetyPressure;
    }

    private void ShowInternals(bool connected)
    {
        InternalsButton.Icon = connected ? KsTguiIconKind.PowerOff : KsTguiIconKind.Times;
        InternalsButton.Text = Loc.GetString(connected
            ? "ks-tgui-atmos-tank-internals-connected"
            : "ks-tgui-atmos-tank-internals-disconnected");
        InternalsButton.Selected = connected;
    }

    private void UpdateRegulatorButtons()
    {
        var release = ReleaseInput.Value;
        MinimumButton.Disabled = MathHelper.CloseTo(release, ReleaseInput.MinValue);
        MaximumButton.Disabled = MathHelper.CloseTo(release, ReleaseInput.MaxValue);
        ResetButton.Disabled = MathHelper.CloseTo(release, Atmospherics.OneAtmosphere);
    }
}
