using System.Globalization;
using Content.Client._KS14.UserInterface.Tgui;
using Content.Shared.Atmos;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._KS14.Atmos.UI;

/// <summary>
///     The gas mixer, after /tg/'s AtmosMixer UI. Exposes the same API as the upstream <c>GasMixerWindow</c>, so
///         <c>GasMixerBoundUserInterface</c> can use either.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class KsTguiGasMixerWindow : KsTguiWindow
{
    public event Action<bool>? ToggleStatusButtonPressed;

    /// <summary>
    ///     The new pressure as text, as the upstream window sends it; the interface parses and clamps it.
    /// </summary>
    public event Action<string>? MixerOutputPressureChanged;

    /// <summary>
    ///     The edited node's new percentage as text. <see cref="NodeOneLastEdited"/> says which node it was.
    /// </summary>
    public event Action<string>? MixerNodePercentageChanged;

    public bool NodeOneLastEdited = true;

    private bool _enabled;

    public KsTguiGasMixerWindow()
    {
        RobustXamlLoader.Load(this);

        MainNodeItem.LabelColor = KsTguiTheme.Foreground(KsTguiTheme.Green);
        SideNodeItem.LabelColor = KsTguiTheme.Foreground(KsTguiTheme.Blue);

        PressureInput.MaxValue = Atmospherics.MaxOutputPressure;
        PressureInput.OnValueChanged += value => MixerOutputPressureChanged?.Invoke(value.ToString(CultureInfo.CurrentCulture));
        MaxButton.OnPressed += _ => PressureInput.SubmitValue(PressureInput.MaxValue);
        PowerButton.OnPressed += _ => ToggleStatusButtonPressed?.Invoke(!_enabled);

        NodeOneInput.OnValueChanged += value => OnNodeChanged(value, nodeOne: true);
        NodeTwoInput.OnValueChanged += value => OnNodeChanged(value, nodeOne: false);

        SetMixerStatus(false);
    }

    public void SetOutputPressure(float pressure)
    {
        PressureInput.Value = pressure;
        MaxButton.Disabled = MathHelper.CloseTo(PressureInput.Value, PressureInput.MaxValue);
    }

    /// <param name="nodeOne">The main node's share, from 0 to 1.</param>
    public void SetNodePercentages(float nodeOne)
    {
        NodeOneInput.Value = nodeOne * 100f;
        NodeTwoInput.Value = 100f - nodeOne * 100f;
    }

    public void SetMixerStatus(bool enabled)
    {
        _enabled = enabled;
        KsTguiPowerButton.Apply(PowerButton, enabled);
    }

    private void OnNodeChanged(float value, bool nodeOne)
    {
        NodeOneLastEdited = nodeOne;

        // The two shares always add up to 100, so move the other one now rather than after the server answers.
        var other = nodeOne ? NodeTwoInput : NodeOneInput;
        other.Value = 100f - value;

        MixerNodePercentageChanged?.Invoke(value.ToString(CultureInfo.CurrentCulture));
    }
}
