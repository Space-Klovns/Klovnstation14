using Content.Client._KS14.UserInterface.Tgui;
using Content.Client.Power.Components;
using Content.Shared.Atmos;
using Content.Shared.Atmos.Piping.Unary.Components;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client._KS14.Atmos.UI;

/// <summary>
///     The heater and freezer, after /tg/'s ThermoMachine UI. Exposes the same API as the upstream
///         <c>GasThermomachineWindow</c>, so <c>GasThermomachineBoundUserInterface</c> can use either:
///         <see cref="ToggleStatusButton"/> raises <c>OnToggled</c> and <see cref="TemperatureSpinbox"/> raises
///         <c>OnValueChanged</c> with <c>Value</c> set, as the upstream controls do.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class KsTguiGasThermomachineWindow : KsTguiWindow
{
    [Dependency] private IEntityManager _entityManager = default!;

    public EntityUid Entity;

    private bool? _active;

    public KsTguiGasThermomachineWindow()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);

        MinimumButton.OnPressed += _ => TemperatureSpinbox.SubmitValue(TemperatureSpinbox.MinValue);
        RoomButton.OnPressed += _ => TemperatureSpinbox.SubmitValue(Atmospherics.T20C);
        MaximumButton.OnPressed += _ => TemperatureSpinbox.SubmitValue(TemperatureSpinbox.MaxValue);

        SetActive(false);
    }

    public void SetActive(bool active)
    {
        // Also undoes a click the server didn't act on.
        ToggleStatusButton.Pressed = active;

        // Called every frame, so only relabel on a change.
        if (_active == active)
            return;

        _active = active;
        KsTguiPowerButton.Apply(ToggleStatusButton, active);
    }

    public void SetTemperature(float temperature)
    {
        TemperatureSpinbox.Value = temperature;
        UpdatePresetButtons();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (_entityManager.TryGetComponent(Entity, out ApcPowerReceiverComponent? receiver))
            SetActive(!receiver.PowerDisabled);

        if (_entityManager.TryGetComponent(Entity, out GasThermoMachineComponent? thermoMachine) &&
            (!MathHelper.CloseTo(TemperatureSpinbox.MinValue, thermoMachine.MinTemperature) ||
             !MathHelper.CloseTo(TemperatureSpinbox.MaxValue, thermoMachine.MaxTemperature)))
        {
            TemperatureSpinbox.MinValue = thermoMachine.MinTemperature;
            TemperatureSpinbox.MaxValue = thermoMachine.MaxTemperature;
            UpdatePresetButtons();
        }
    }

    private void UpdatePresetButtons()
    {
        var target = TemperatureSpinbox.Value;
        MinimumButton.Disabled = MathHelper.CloseTo(target, TemperatureSpinbox.MinValue);
        RoomButton.Disabled = MathHelper.CloseTo(target, Atmospherics.T20C) ||
                              Atmospherics.T20C < TemperatureSpinbox.MinValue ||
                              Atmospherics.T20C > TemperatureSpinbox.MaxValue;
        MaximumButton.Disabled = MathHelper.CloseTo(target, TemperatureSpinbox.MaxValue);
    }
}
