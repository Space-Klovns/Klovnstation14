    const storage = {
        get() {
            try {
                return window.localStorage.getItem(LANGUAGE_KEY);
            } catch {
                return null;
            }
        },
        set(value) {
            try {
                window.localStorage.setItem(LANGUAGE_KEY, value);
            } catch {
                // Storage unavailable; the choice just won't be remembered.
            }
        },
    };

    // The language to use for a tag like "pt-BR" or "ru-RU": an exact match, then the primary subtag ("ru"), then a
    //      language whose tag starts with it ("pt" -> "pt-BR").
    function match(tag) {
        if (typeof tag !== "string" || tag.length === 0)
            return null;

        const lower = tag.toLowerCase();
        const codes = Object.keys(LANGUAGES);
        const exact = codes.find((code) => code.toLowerCase() === lower);
        if (exact)
            return exact;

        const primary = lower.split("-")[0];
        return codes.find((code) => code.toLowerCase() === primary) ??
            codes.find((code) => code.toLowerCase().split("-")[0] === primary) ??
            null;
    }

    function detect() {
        const saved = storage.get();
        if (saved && LANGUAGES[saved])
            return saved;

        return match(document.documentElement.lang) ?? "en";
    }

    let current = detect();

    // Looks up a string and fills in {placeholders}.
    function t(key, params) {
        let text = LANGUAGES[current].strings[key] ?? LANGUAGES.en.strings[key] ?? key;
        if (params) {
            for (const [name, value] of Object.entries(params))
                text = text.split(`{${name}}`).join(String(value));
        }

        return text;
    }

    // Whether a key exists (in English, which has every key), for text picked by a server-sent reason.
    function has(key) {
        return Object.prototype.hasOwnProperty.call(LANGUAGES.en.strings, key);
    }

